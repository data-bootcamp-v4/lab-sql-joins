-- Identify the film categories with the longest average running time.
SELECT c.name AS category, AVG(f.length) AS average_running_time
FROM film f
JOIN film_category fc ON f.film_id = fc.film_id
JOIN category c ON fc.category_id = c.category_id
GROUP BY c.name
ORDER BY average_running_time DESC
LIMIT 1; -- This will show the category with the longest average running time

-- Display the top 10 most frequently rented movies in descending order.
SELECT f.title, COUNT(r.rental_id) AS rental_count
FROM rental r
JOIN inventory i ON r.inventory_id = i.inventory_id
JOIN film f ON i.film_id = f.film_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 10;

-- Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT f.title, COUNT(i.inventory_id) AS available_copies
FROM inventory i
JOIN film f ON i.film_id = f.film_id
LEFT JOIN rental r ON i.inventory_id = r.inventory_id AND r.return_date IS NULL
WHERE f.title = 'Academy Dinosaur' AND i.store_id = 1
GROUP BY f.title 
HAVING available_copies > 0;

/*# Provide a list of all distinct film titles, along with their availability status in the inventory. 
# Include a column indicating whether each title is 'Available' or 'NOT available.' 
#Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL." */
SELECT f.title, 
       CASE 
           WHEN IFNULL(available.available, 0) > 0 THEN 'Available'
           ELSE 'NOT available'
       END AS availability
FROM film f
LEFT JOIN (
    SELECT i.film_id, 
           COUNT(i.inventory_id) - COUNT(r.rental_id) AS available
    FROM inventory i
    LEFT JOIN rental r ON i.inventory_id = r.inventory_id AND r.return_date IS NULL
    GROUP BY i.film_id
) AS available ON f.film_id = available.film_id
ORDER BY f.title;