USE sakila;


SELECT * FROM film;
SELECT * FROM category;

SELECT c.name AS category_name, COUNT(f.film_id) AS number_of_films
FROM category AS c
INNER JOIN film_category AS fc
ON c.category_id = fc.category_id
INNER JOIN film as f
ON fc.film_id = f.film_id
GROUP BY c.name;

-- Retrieve the store ID, city, and country for each store.

SELECT * FROM store;
SELECT * FROM city;
SELECT * FROM country;
SELECT * FROM address;

SELECT s.store_id, c.city, ct.country
FROM store AS s
INNER JOIN address AS a
ON s.address_id = a.address_id
INNER JOIN city AS c
ON a.city_id = c.city_id
INNER JOIN country AS ct
ON c.country_id = ct.country_id;

-- Calculate the total revenue generated by each store in dollars.

SELECT * FROM store;
SELECT * FROM inventory;
SELECT * FROM rental;
SELECT * FROM payment;

SELECT s.store_id, SUM(p.amount) AS total_amount
FROM store AS s
INNER JOIN inventory AS i
ON s.store_id = i.store_id
INNER JOIN rental AS r
ON i.inventory_id = r.inventory_id
INNER JOIN payment AS p
ON r.rental_id = p.rental_id
GROUP BY store_id;

-- Determine the average running time of films for each category

SELECT * FROM film;
SELECT * FROM film_category;
SELECT * FROM category;

SELECT AVG(f.length) AS avg_length, fc.category_id, c.name
FROM film AS f
INNER JOIN film_category as fc
ON f.film_id = fc.film_id
INNER JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name, fc.category_id;

-- Identify the film categories with the longest average running time.

SELECT AVG(f.length) AS avg_length, fc.category_id, c.name
FROM film AS f
INNER JOIN film_category as fc
ON f.film_id = fc.film_id
INNER JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name, fc.category_id
ORDER BY avg_length DESC;

-- Display the top 10 most frequently rented movies in descending order.

SELECT * FROM film;
SELECT * FROM inventory;
SELECT * FROM rental;

SELECT f.film_id, f.title, COUNT(r.rental_id) AS rented_times
FROM film AS f
INNER JOIN inventory as i
ON f.film_id = i.film_id
INNER JOIN rental AS r
ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rented_times DESC;
