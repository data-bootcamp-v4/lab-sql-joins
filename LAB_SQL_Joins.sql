USE `sakila`;

-- =============================================
-- Challenge - Joining on multiple tables
-- =============================================
-- Write SQL queries to perform the following tasks using the Sakila database:

-- 1. List the number of films per category.
SELECT fc.category_id AS films_per_category, COUNT(f.film_id) as number_film
FROM film_category AS fc
JOIN film AS  f
ON fc.film_id = f.film_id
GROUP BY films_per_category;

-- 2. Retrieve the store ID, city, and country for each store.
SELECT s.store_id, c.city, co.country
FROM store AS s
INNER JOIN address AS a ON s.address_id = a.address_id 
INNER JOIN city AS c ON a.city_id = c.city_id
INNER JOIN country AS co ON c.country_id = co.country_id
GROUP BY s.store_id;

-- 3. Calculate the total revenue generated by each store in dollars.
SELECT s.store_id, SUM(p.amount) AS total_revenue
FROM store AS s
INNER JOIN staff AS st ON s.manager_staff_id = st.staff_id
INNER JOIN payment AS p on p.staff_id = st.staff_id
GROUP BY s.store_id;


-- 4. Determine the average running time of films for each category.
SELECT fcat.category_id, AVG(f.length) AS avg_running_time, cat.name AS category_name
FROM film AS f
JOIN film_category AS fcat ON f.film_id = fcat.film_id
JOIN category AS cat ON fcat.category_id = cat.category_id
GROUP BY fcat.category_id, category_name;

-- ===========================
-- Bonus:
-- ===========================
-- 5. Identify the film categories with the longest average running time.
SELECT fcat.category_id, (AVG(f.length)) AS avg_running_time, cat.name AS category_name
FROM film AS f
JOIN film_category AS fcat ON f.film_id = fcat.film_id
JOIN category AS cat ON fcat.category_id = cat.category_id
GROUP BY fcat.category_id, category_name
ORDER BY avg_running_time DESC
LIMIT 1;

-- 6. Display the top 10 most frequently rented movies in descending order.
SELECT COUNT(r.rental_id) AS rental_count,  f.film_id, f.title
FROM rental AS r
LEFT JOIN inventory AS i ON r.inventory_id = i.inventory_id
RIGHT JOIN  film AS f ON i.film_id = f.film_id
GROUP BY f.film_id, f.title
ORDER BY rental_count DESC
LIMIT 10;
-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT f.title, s.store_id
FROM film AS f
INNER JOIN inventory AS i ON f.film_id = i.film_id
LEFT JOIN store AS s ON i.store_id = s.store_id
WHERE f.title = 'Academy Dinosaur'
	AND s.store_id = 1;
