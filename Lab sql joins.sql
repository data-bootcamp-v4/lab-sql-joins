use sakila;

-- 1. List the number of films per category.
select * from category;
select * from film_category;

select c.name, fc.category_id, count(*) from film_category fc
join category c
on c.category_id = fc.category_id
group by fc.category_id;


-- 2. Retrieve the store ID, city, and country for each store.
select * from address;
select * from store;
select * from city;

select co.country, c.city, ad.address, s.store_id from store s
join address ad
on s.address_id = ad.address_id
join city c 
on c.city_id = ad.city_id
join country co 
on c.country_id = co.country_id;

-- 3.  Calculate the total revenue generated by each store in dollars.
select * from payment;

select s.store_id, sum(p.amount) from payment p
join staff st 
on p.staff_id = st.staff_id
join store s 
on st.store_id = s.store_id
group by s.store_id;

-- 4.  Determine the average running time of films for each category.

select c.name, avg(f.length) from film f 
join film_category fc
on f.film_id = fc.film_id
join category c 
on c.category_id = fc.category_id
group by c.name;

-- 5.  Identify the film categories with the longest average running time.

select category_name, avg_length_film from
(select c.name as category_name, avg(f.length) as avg_length_film from film f 
join film_category fc
on f.film_id = fc.film_id
join category c 
on c.category_id = fc.category_id
group by c.name) as avg_length
order by avg_length_film desc
limit 1; 

-- 6.  Display the top 10 most frequently rented movies in descending order.

select  f.title, count(r.rental_id) as rental_count  from film f 
join inventory i 
on i.film_id = f.film_id
join rental r 
on r.inventory_id = i.inventory_id
group by f.title
order by rental_count desc
limit 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.

select s.store_id, f.title from film f 
join inventory i on i.film_id = f.film_id
join store s on s.store_id = i.store_id
where f.title = "Academy Dinosaur"
and s.store_id = 1;

-- 8. Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a `CASE` statement combined with `IFNULL`."

select f.title, 
case 
when inv.inventory_count > 0 then'Available'
        else 'NOT available'
    end as availability_status 
 from film f 
left join (select i.film_id, 
COUNT(i.inventory_id) AS inventory_count 
from inventory i 
group by i.film_id) as inv 
on inv.film_id = f.film_id;

select i.film_id, COUNT(i.inventory_id) AS inventory_count from inventory i 
group by i.film_id;