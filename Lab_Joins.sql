-- ------------------------
-- Retrieve the store ID, city, and country for each store.
SELECT s.store_id, ci.city, co.country
FROM store AS s
LEFT JOIN address AS a ON s.address_id = a.address_id
LEFT JOIN city AS ci ON a.city_id = ci.city_id
LEFT JOIN country AS co ON ci.country_id = co.country_id;

-- ------------------------
-- Calculate the total revenue generated by each store in dollars.
SELECT st.store_id, CONCAT('$ ', FORMAT(SUM(p.amount), 2)) AS total_revenue 
FROM payment AS p
JOIN staff AS s ON p.staff_id = s.staff_id 
JOIN store AS st ON s.store_id = st.store_id
GROUP BY store_id
ORDER BY total_revenue DESC;

-- ------------------------
-- Determine the average running time of films for each category.
SELECT fc.category_id AS category, AVG(length) AS avg_running_time FROM film AS f 
JOIN film_category AS fc ON f.film_id = fc.film_id GROUP BY fc.category_id;