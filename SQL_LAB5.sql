USE sakila;
SHOW TABLES;
-- List the number of films per category
SELECT 
    c.name, 
    COUNT(fc.film_id) AS num_films 
FROM category c
INNER JOIN film_category fc
    ON c.category_id = fc.category_id
GROUP BY c.name;

-- Retrieve the store ID, city, and country for each store.
SELECT
    s.store_id, 
    ci.city, 
    co.country -- 1. Seleccionamos las tres columnas
FROM store s 
INNER JOIN address a 
    ON s.address_id = a.address_id -- 2. store -> address por address_id
INNER JOIN city ci 
    ON a.city_id = ci.city_id -- 3. address -> city por city_id
INNER JOIN country co 
    ON ci.country_id = co.country_id; -- 4. city -> country por country_id
    
-- Calculate the total revenue generated by each store in dollars.
SELECT
    s.store_id,
    -- 1. SUMA el campo 'amount' de la tabla 'payment'
    SUM(p.amount) AS total_revenue 
FROM store s
-- 2. Unimos Tienda con Empleado (por el ID de la tienda)
INNER JOIN staff st
    ON s.store_id = st.store_id
-- 3. Unimos Empleado con Pagos (por el ID del empleado)
INNER JOIN payment p
    ON st.staff_id = p.staff_id
-- 4. Agrupamos por ID de tienda para obtener la suma por grupo
GROUP BY s.store_id;

-- Determine the average running time of films for each category.
SELECT
    c.name AS category_name,
    ROUND(AVG(f.length), 2) AS avg_duration
FROM category c
INNER JOIN film_category fc
    ON c.category_id = fc.category_id -- 1. Conexión de Nombre a Enlace
INNER JOIN film f
    ON fc.film_id = f.film_id -- 2. Conexión de Enlace a Dato
GROUP BY c.name
ORDER BY avg_duration DESC; -- Ordenamos el resultado final por la duración media

-- Identify the film categories with the longest average running time. 
SELECT
    c.name AS category_name,
    ROUND(AVG(f.length), 2) AS avg_duration
FROM category c
INNER JOIN film_category fc
    ON c.category_id = fc.category_id
INNER JOIN film f
    ON fc.film_id = f.film_id
GROUP BY c.name
ORDER BY avg_duration DESC
LIMIT 1; -- Muestra solo la primera fila (la más larga)

-- Display the top 10 most frequently rented movies in descending order.
SELECT
    f.title,
    COUNT(r.rental_id) AS rental_count -- 1. Contamos los registros de alquiler
FROM film f
INNER JOIN inventory i 
    ON f.film_id = i.film_id -- 2. film (título) se une a inventory (copias) por film_id
INNER JOIN rental r
    ON i.inventory_id = r.inventory_id -- 3. inventory se une a rental (transacciones) por inventory_id
GROUP BY f.title -- 4. Agrupamos por título para que COUNT funcione por película
ORDER BY rental_count DESC -- 5. Ordenamos del más alquilado al menos alquilado
LIMIT 10; -- 6. Limitamos la salida a las 10 mejores

-- Determine if "Academy Dinosaur" can be rented from Store 1. 
SELECT
    f.title,
    i.inventory_id
FROM film f
INNER JOIN inventory i
    ON f.film_id = i.film_id -- 1. Unimos Película con Inventario por film_id
WHERE
    f.title = 'ACADEMY DINOSAUR' -- 2. Filtramos la película específica
    AND i.store_id = 1; -- 3. Filtramos la tienda específica

-- Provide a list of all distinct film titles, along with their availability status in the inventory...

SELECT
    f.title,
    -- 1. Contamos cuántas copias hay en el inventario para ese título.
    COUNT(i.inventory_id) AS num_copies, 
    -- 2. Usamos CASE para determinar la disponibilidad basado en el conteo.
    CASE
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film f
-- 3. LEFT JOIN asegura que se listen TODAS las películas (tabla izquierda), incluso si no tienen coincidencias en el inventario (tabla derecha).
LEFT JOIN inventory i
    ON f.film_id = i.film_id
GROUP BY f.title, f.film_id -- 4. Agrupamos por película
ORDER BY f.title;