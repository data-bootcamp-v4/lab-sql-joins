-- CHALLENGES
-- 1. List the number of films per category.

SELECT * FROM film_category;
SELECT * FROM category;

SELECT cat.name AS category_name, count(fc.film_id) AS num_films
FROM category AS cat
LEFT JOIN film_category as fc
ON cat.category_id = fc.category_id
GROUP BY category_name;

-- 2. Retrieve the store ID, city, and country for each store.
-- store | store_id | city | country

SELECT
	sto.store_id AS 'store',
    ci.city AS 'city',
    co.country AS 'country'
FROM store AS sto
JOIN address AS ad
ON sto.address_id = ad.address_id
JOIN city as ci
ON ad.city_id = ci.city_id
JOIN country AS co
ON ci.country_id = co.country_id;

-- 3. Calculate the total revenue generated by each store in dollars.

SELECT * FROM payment;

-- Option 1 via Staff
SELECT store_id, sum(amount) AS total_revenue
FROM payment AS p
JOIN staff as stf
ON p.staff_id = stf.staff_id
GROUP BY store_id;

-- Option 2 via store rental location
SELECT inv.store_id, sum(p.amount) as total_revenue
FROM payment as p
JOIN rental as r
ON p.rental_id = r.rental_id
JOIN inventory as inv
ON r.inventory_id =inv.inventory_id
GROUP BY inv.store_id;

-- 4. Determine the average running time of films for each category.

SELECT cat.name AS category_name, avg(film.length) AS avg_film_length
FROM film AS film
JOIN film_category as fc
ON film.film_id = fc.film_id
JOIN category as cat
ON cat.category_id = fc.category_id
GROUP BY category_name;

-- 5.Identify the film categories with the longest average running time.
SELECT cat.name AS category_name, avg(film.length) AS avg_film_length
FROM film AS film
JOIN film_category as fc
ON film.film_id = fc.film_id
JOIN category as cat
ON cat.category_id = fc.category_id
GROUP BY category_name
ORDER BY avg_film_length DESC;

-- 6. Display the top 10 most frequently rented movies in descending order.
-- | TITLE | FILM_ID | INVENTORY_ID | COUNT(RENTAL_DATE) |
-- FILM --> INVENTORY --> RENTAL

SELECT title, count(rental_id) AS 'rental_count'
FROM film as fi
JOIN inventory as inv
ON fi.film_id = inv.film_id
JOIN rental as r
ON inv.inventory_id = r.inventory_id
GROUP BY title
ORDER BY rental_count DESC
LIMIT 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT title, store_id
FROM film as fi
JOIN inventory as inv
ON fi.film_id = inv.film_id
WHERE title = 'Academy Dinosaur' AND inv.store_id = 1;

