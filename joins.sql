-- Challenge 1 - Question 1: Number of films per category

SELECT
    category.name,
    COUNT(*) AS number_of_films
FROM film
JOIN film_category
    ON film.film_id = film_category.film_id
JOIN category
    ON category.category_id = film_category.category_id
GROUP BY category.name
ORDER BY number_of_films DESC;

-- Challenge 1 - Question 2: Store ID, city and country

SELECT
    store.store_id,
    city.city,
    country.country
FROM store
JOIN address
    ON store.address_id = address.address_id
JOIN city
    ON address.city_id = city.city_id
JOIN country
    ON city.country_id = country.country_id;

-- Challenge 1 - Question 3: Total revenue generated by each store

SELECT
    store.store_id,
    SUM(payment.amount) AS total_revenue
FROM store
JOIN staff
    ON store.store_id = staff.store_id
JOIN payment
    ON staff.staff_id = payment.staff_id
GROUP BY store.store_id;

-- Challenge 1 - Question 4: Average running time of films for each category

SELECT
    category.name,
    ROUND(AVG(film.length), 2) AS average_duration
FROM film
JOIN film_category
    ON film.film_id = film_category.film_id
JOIN category
    ON film_category.category_id = category.category_id
GROUP BY category.name
ORDER BY average_duration DESC;

-- Bonus 5: Film category with the longest average running time

SELECT
    category.name,
    ROUND(AVG(film.length), 2) AS average_duration
FROM film
JOIN film_category
    ON film.film_id = film_category.film_id
JOIN category
    ON film_category.category_id = category.category_id
GROUP BY category.name
ORDER BY average_duration DESC
LIMIT 1;

-- Bonus 6: Top 10 most frequently rented movies

SELECT
    film.title,
    COUNT(*) AS rental_count
FROM film
JOIN inventory
    ON film.film_id = inventory.film_id
JOIN rental
    ON inventory.inventory_id = rental.inventory_id
GROUP BY film.title
ORDER BY rental_count DESC
LIMIT 10;

-- Bonus 7: Check if "Academy Dinosaur" is available in Store 1

SELECT
    film.title,
    inventory.store_id
FROM film
JOIN inventory
    ON film.film_id = inventory.film_id
WHERE film.title = 'Academy Dinosaur'
AND inventory.store_id = 1;

-- Bonus 8: Film availability

SELECT
    film.title,
    CASE
        WHEN IFNULL(inventory.inventory_id, 0) = 0
        THEN 'NOT available'
        ELSE 'Available'
    END AS availability
FROM film
LEFT JOIN inventory
    ON film.film_id = inventory.film_id
GROUP BY film.title, inventory.inventory_id;




