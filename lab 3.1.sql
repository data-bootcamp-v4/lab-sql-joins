-- Write SQL queries to perform the following tasks using the Sakila database:

# List the number of films per category.
SELECT fc.category_id, c.name, COUNT(film_id) as films_per_category
FROM film_category as fc
JOIN category as c
ON fc.category_id = c.category_id
GROUP BY category_id;


# Retrieve the store ID, city, and country for each store. 
SELECT * FROM country;
SELECT * FROM address;

SELECT s.store_id, city.city, country.country
FROM store as s
JOIN address as ad 
ON s.address_id = ad.address_id
JOIN city 
ON city.city_id = ad.city_id 
JOIN country 
ON city.country_id = country.country_id
;

# Calculate the total revenue generated by each store in dollars.
SELECT * FROM staff;
SELECT * FROM payment;

SELECT staff.store_id, SUM(pay.amount)
FROM payment as pay
JOIN staff
ON pay.staff_id = staff.staff_id 
GROUP BY staff.staff_id
; 

