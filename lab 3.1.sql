SELECT store.store_id, f.title 
FROM inventory as inv 
JOIN film as f 
ON inv.film_id = f.film_id 
JOIN store 
ON inv.store_id = store.store_id 
WHERE f.title LIKE "%Academy Dinosaur%" AND store.store_id = 1
GROUP BY store.store_id, f.title
;

