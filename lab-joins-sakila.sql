USE sakila;

-- 1. List the number of films per category.
SELECT * FROM film; -- film_id
SELECT * FROM category; -- category_id
SELECT * FROM film_category; -- film_id & category_id

SELECT c.name AS category, COUNT(f.title) AS film_count
FROM film AS f
	JOIN film_category AS fc
		ON f.film_id = fc.film_id
	JOIN category AS c
		ON c.category_id = fc.category_id
GROUP BY c.name
;

-- 2. Retrieve the store ID, city, and country for each store.
SELECT * FROM store; -- address_id
SELECT * FROM address; -- address_id, city_id
SELECT * FROM city; -- city_id, country_id
SELECT * FROM country; -- country_id

SELECT s.store_id, c.city, cou.country
FROM store AS s
	JOIN address AS a
		ON a.address_id = s.address_id
	JOIN city AS c
		ON c.city_id = a.city_id
	JOIN country AS cou
		ON c.country_id = cou.country_id
;

-- 3. Calculate the total revenue generated by each store in dollars.
SELECT * FROM store; -- story_id
SELECT * FROM inventory; -- story_id, inventory_id
SELECT * FROM rental; -- inventory_id, rental_id
SELECT * FROM payment; -- rental_id

SELECT s.store_id, SUM(p.amount) AS tot_revenue
FROM store AS s
	JOIN inventory AS i
		ON i.store_id = s.store_id
	JOIN rental AS r
		ON r.inventory_id = i.inventory_id
	JOIN payment AS p
		ON r.rental_id = p.rental_id
GROUP BY s.store_id
;


-- 4. Determine the average running time of films for each category.
SELECT c.name AS category, AVG(f.length) AS avg_running_time
FROM film AS f
	JOIN film_category AS fc
		ON f.film_id = fc.film_id
	JOIN category AS c
		ON c.category_id = fc.category_id
GROUP BY category
;


