USE sakila;

-- List the number of films per category.
SELECT 
    category.name AS category,
    COUNT(film_category.film_id) AS number_films
FROM category
JOIN film_category ON category.category_id = film_category.category_id
GROUP BY category.name
ORDER BY number_films DESC;


-- Retrieve the store ID, city, and country for each store.
SELECT
	store.store_id,
    city.city,
    country.country
FROM store
JOIN address ON store.address_id = address.address_id
JOIN city ON address.city_id = city.city_id
JOIN country ON city.country_id = country.country_id;

-- Calculate the total revenue generated by each store in dollars.
SELECT
    store.address_id,
    ROUND(SUM(payment.amount), 2) AS total_revenue
FROM store
JOIN staff ON store.store_id = staff.store_id
JOIN payment ON staff.staff_id = payment.staff_id
GROUP BY store.store_id
ORDER BY total_revenue DESC;

-- Determine the average running time of films for each category.
SELECT
    category.name AS category,
    ROUND(AVG(film.length), 2) as avg_running_time
FROM category
JOIN film_category ON category.category_id = film_category.category_id
JOIN film ON film_category.film_id = film.film_id
GROUP BY category.name
ORDER BY avg_running_time DESC;

-- Identify the film categories with the longest average running time.
SELECT
    category.name AS category,
    ROUND(AVG(film.length), 2) as avg_running_time
FROM category
JOIN film_category ON category.category_id = film_category.category_id
JOIN film ON film_category.film_id = film.film_id
GROUP BY category.name
ORDER BY avg_running_time DESC
LIMIT 5;


-- Display the top 10 most frequently rented movies in descending order.
SELECT
    film.title,
    COUNT(rental.rental_id) AS times_rented
FROM film
JOIN inventory ON film.film_id = inventory.film_id
JOIN rental ON inventory.inventory_id = rental.inventory_id
GROUP BY film.title
ORDER BY times_rented DESC 
LIMIT 10;
	 

-- Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT
    film.title,
    inventory.store_id,
    COUNT(inventory.inventory_id) AS copies_store
FROM film
JOIN inventory ON film.film_id = inventory.film_id
WHERE film.title = 'Academy Dinosaur' AND inventory.store_id = 1
GROUP BY film.title, inventory.store_id;
    

-- Provide a list of all distinct film titles, along with their availability status in the inventory. Include a column indicating whether each title is 'Available' or 'NOT available.' Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL
SELECT DISTINCT
    film.title,
    CASE
       WHEN IFNULL(inventory.inventory_id, 0) = 0 THEN 'NOT Available'
       ELSE 'Available'
	END AS availability
FROM film
LEFT JOIN inventory ON film.film_id = inventory.film_id
ORDER BY film.title;

