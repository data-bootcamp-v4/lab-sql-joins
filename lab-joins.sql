USE sakila;

-- List the number of films per category.
SELECT * FROM film_category;
SELECT * FROM category;


SELECT COUNT(f.film_id) AS Number_of_films, c.name AS Category_name
FROM film_category AS f
LEFT JOIN category AS c
ON f.category_id = c.category_id
GROUP BY Category_name;

-- Retrieve the store ID, city, and country for each store.
SELECT * FROM address;
SELECT * FROM city;
SELECT * FROM country;

SELECT s.store_id, ci.city, co.country 
FROM store AS s
JOIN address AS a
ON s.address_id = a.address_id
JOIN city AS ci
ON a.city_id = ci.city_id
JOIN country AS co
ON ci.country_id = co.country_id;

-- Calculate the total revenue generated by each store in dollars.
SELECT * FROM payment;
SELECT * FROM staff;

SELECT s.store_id, SUM(p.amount) AS total_revenue
FROM store AS s
LEFT JOIN staff AS st 
ON s.store_id = st.store_id
LEFT JOIN payment AS p 
ON st.staff_id = p.staff_id
GROUP BY s.store_id;

-- Determine the average running time of films for each category.
SELECT c.name AS Category_name, ROUND(AVG(f.length)) AS average_running_time
FROM film AS f
LEFT JOIN film_category AS fc
ON f.film_id = fc.film_id
LEFT JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY Category_name;

-- Identify the film categories with the longest average running time.
SELECT c.name AS Category_name, ROUND(AVG(f.length)) AS average_running_time
FROM film AS f
LEFT JOIN film_category AS fc
ON f.film_id = fc.film_id
LEFT JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY Category_name
ORDER BY average_running_time DESC
LIMIT 1;

-- Display the top 10 most frequently rented movies in descending order.
SELECT title, COUNT(rental_id) AS rent_count 
FROM film AS f
LEFT JOIN inventory AS i
ON f.film_id = i.film_id
LEFT JOIN rental AS r
ON i.inventory_id = r.inventory_id
GROUP BY title
ORDER BY rent_count DESC
LIMIT 10;


-- Determine if "Academy Dinosaur" can be rented from Store 1.

SELECT title, store_id
FROM film AS f
LEFT JOIN inventory AS i
ON f.film_id = i.film_id
WHERE title = 'Academy Dinosaur';

