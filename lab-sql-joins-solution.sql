-- 4) Determine the average running time (length) of films for each category.
SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS avg_length_minutes
FROM category AS c
JOIN film_category AS fc
    ON fc.category_id = c.category_id
JOIN film AS f
    ON f.film_id = fc.film_id
GROUP BY c.category_id, c.name
ORDER BY avg_length_minutes DESC, c.name;

-- BONUS A) Film category (or categories) with the longest average running time.
-- Option 1: LIMIT 1
SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS avg_length_minutes
FROM category AS c
JOIN film_category AS fc
    ON fc.category_id = c.category_id
JOIN film AS f
    ON f.film_id = fc.film_id
GROUP BY c.category_id, c.name
ORDER BY avg_length_minutes DESC
LIMIT 1;

-- Option 2: Return all categories tied for the maximum average length.
SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS avg_length_minutes
FROM category AS c
JOIN film_category AS fc
    ON fc.category_id = c.category_id
JOIN film AS f
    ON f.film_id = fc.film_id
GROUP BY c.category_id, c.name
HAVING AVG(f.length) = (
    SELECT MAX(avg_len)
    FROM (
        SELECT AVG(f2.length) AS avg_len
        FROM category c2
        JOIN film_category fc2
            ON fc2.category_id = c2.category_id
        JOIN film f2
            ON f2.film_id = fc2.film_id
        GROUP BY c2.category_id
    ) AS t
)
ORDER BY category;

-- BONUS B) Top 10 most frequently rented movies (descending).
SELECT
    f.title,
    COUNT(*) AS rental_count
FROM rental AS r
JOIN inventory AS i
    ON i.inventory_id = r.inventory_id
JOIN film AS f
    ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY rental_count DESC, f.title
LIMIT 10;

-- BONUS C) Determine if "Academy Dinosaur" can be rented from Store 1 *right now*.
-- We consider a copy available if there exists at least one inventory item in store 1
-- that is NOT currently out on a rental (i.e., no open rental with return_date IS NULL).
SELECT
    CASE WHEN COUNT(*) > 0 THEN 'Available' ELSE 'NOT available' END AS status
FROM inventory AS i
JOIN film AS f
    ON f.film_id = i.film_id
LEFT JOIN rental AS r
    ON r.inventory_id = i.inventory_id
    AND r.return_date IS NULL
WHERE f.title = 'Academy Dinosaur'
  AND i.store_id = 1
  AND r.rental_id IS NULL;

-- BONUS D) List all DISTINCT film titles with an availability flag in inventory.
-- The lab hint suggests using CASE with IFNULL and notes there are 42 titles not in inventory.
-- Here availability simply means: at least one row exists in inventory for that film_id.
SELECT
    f.title,
    CASE
        WHEN COUNT(i.inventory_id) = 0 THEN 'NOT available'
        ELSE 'Available'
    END AS availability
FROM film AS f
LEFT JOIN inventory AS i
    ON i.film_id = f.film_id
GROUP BY f.film_id, f.title
ORDER BY f.title;

