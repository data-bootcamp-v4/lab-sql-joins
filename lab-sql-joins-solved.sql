USE sakila;


-- 1. Number of films per category
SELECT
    c.name AS category,
    COUNT(fc.film_id) AS number_of_films
FROM category AS c
LEFT JOIN film_category AS fc
    ON c.category_id = fc.category_id
GROUP BY c.category_id, c.name
ORDER BY number_of_films DESC, category;


-- 2. Store ID, city, and country for each store
SELECT
    s.store_id,
    ci.city,
    co.country
FROM store AS s
JOIN address AS a
    ON s.address_id = a.address_id
JOIN city AS ci
    ON a.city_id = ci.city_id
JOIN country AS co
    ON ci.country_id = co.country_id
ORDER BY s.store_id;


-- 3. Total revenue generated by each store
-- A LEFT JOIN keeps stores in the result even if they have no payments.
SELECT
    s.store_id,
    ROUND(COALESCE(SUM(p.amount), 0), 2) AS total_revenue
FROM store AS s
LEFT JOIN inventory AS i
    ON s.store_id = i.store_id
LEFT JOIN rental AS r
    ON i.inventory_id = r.inventory_id
LEFT JOIN payment AS p
    ON r.rental_id = p.rental_id
GROUP BY s.store_id
ORDER BY s.store_id;


-- 4. Average running time of films for each category
SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS average_running_time_minutes
FROM category AS c
JOIN film_category AS fc
    ON c.category_id = fc.category_id
JOIN film AS f
    ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY average_running_time_minutes DESC, category;


-- 5. Film categories with the longest average running time
-- This returns all categories tied for the longest average.
WITH category_average_lengths AS (
    SELECT
        c.category_id,
        c.name AS category,
        AVG(f.length) AS average_running_time_minutes
    FROM category AS c
    JOIN film_category AS fc
        ON c.category_id = fc.category_id
    JOIN film AS f
        ON fc.film_id = f.film_id
    GROUP BY c.category_id, c.name
)
SELECT
    category,
    ROUND(average_running_time_minutes, 2) AS average_running_time_minutes
FROM category_average_lengths
WHERE average_running_time_minutes = (
    SELECT MAX(average_running_time_minutes)
    FROM category_average_lengths
);


-- 6. Top 10 most frequently rented movies
SELECT
    f.title,
    COUNT(r.rental_id) AS times_rented
FROM film AS f
JOIN inventory AS i
    ON f.film_id = i.film_id
JOIN rental AS r
    ON i.inventory_id = r.inventory_id
GROUP BY f.film_id, f.title
ORDER BY times_rented DESC, f.title
LIMIT 10;


-- 7. Can "Academy Dinosaur" be rented from Store 1?
SELECT
    f.title,
    1 AS store_id,
    CASE
        WHEN COUNT(i.inventory_id) > 0 THEN 'Yes'
        ELSE 'No'
    END AS can_be_rented
FROM film AS f
LEFT JOIN inventory AS i
    ON f.film_id = i.film_id
    AND i.store_id = 1
WHERE f.title = 'Academy Dinosaur'
GROUP BY f.film_id, f.title;


-- 8. Availability of every distinct film title
-- IFNULL and CASE identify titles with no inventory records.
SELECT
    f.title,
    CASE
        WHEN IFNULL(COUNT(i.inventory_id), 0) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film AS f
LEFT JOIN inventory AS i
    ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY f.title;
