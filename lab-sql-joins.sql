-- Challenge - Joining on multiple tables using the Sakila database:

-- 1. List the number of films per category.

SELECT 
    c.name AS category_name,
    COUNT(fc.film_id) AS number_of_films
FROM
    category c
        JOIN
    film_category fc ON c.category_id = fc.category_id
GROUP BY category_name
ORDER BY category_name;

-- 2. Retrieve the store ID, city, and country for each store.

SELECT 
    s.store_id, 
    c.city_id AS store_city, 
    c.country_id AS store_country
FROM
    store s
JOIN 
    address a ON s.address_id = a.address_id
JOIN 
    city c ON a.city_id = c.city_id;

-- 3. Calculate the total revenue generated by each store in dollars.

SELECT 
    s.store_id, SUM(p.amount) AS total_revenue
FROM
    payment p
        JOIN
    rental r ON p.rental_id = r.rental_id
        JOIN
    inventory i ON r.inventory_id = i.inventory_id
        JOIN
    store s ON i.store_id = s.store_id
GROUP BY s.store_id;


-- 4. Determine the average running time of films for each category.
SELECT 
    c.name, AVG(f.length) AS average_length
FROM
    category c
        JOIN
    film_category fc ON c.category_id = fc.category_id
        JOIN
    film f ON fc.film_id = f.film_id
GROUP BY c.name;


-- Bonus:
-- 5. Identify the film categories with the longest average running time.

SELECT 
    c.name, AVG(f.length) AS average_length
FROM
    category c
        JOIN
    film_category fc ON c.category_id = fc.category_id
        JOIN
    film f ON fc.film_id = f.film_id
GROUP BY c.name
ORDER BY average_length DESC;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.

SELECT 
    f.title, i.store_id
FROM
    film f
        JOIN
    inventory i ON f.film_id = i.film_id
        JOIN
    store s ON i.store_id = s.store_id
WHERE
    f.title = 'Academy Dinosaur'
        AND s.store_id = 1
;

SELECT 
    f.title,
    s.store_id,
    COUNT(i.inventory_id) AS available_copies
FROM
    film f
        JOIN
    inventory i ON f.film_id = i.film_id
        JOIN
    store s ON i.store_id = s.store_id
WHERE
    f.title = 'Academy Dinosaur'
        AND s.store_id = 1
GROUP BY f.title , s.store_id;

-- 8. Provide a list of all distinct film titles, along with their availability status in the inventory. Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL.

SELECT 
    f.title,
    CASE
        WHEN IFNULL(MAX(i.inventory_id), 0) = 0 THEN 'NOT available'
        ELSE 'Available'
    END AS availability
FROM
    film f
        LEFT JOIN
    inventory i ON f.film_id = i.film_id
GROUP BY f.title;