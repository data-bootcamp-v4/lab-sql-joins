-- Write SQL queries to perform the following tasks using the Sakila database:
USE sakila;

-- 1.List the number of films per category.
select * from film;   			-- 1000 
select * from category;			-- 16
select * from film_category;	-- 1000

select c.name, count(f.film_id) from film as f
join film_category as fm
ON fm.film_id = f.film_id 
JOIN category as c
on fm.category_id = c.category_id
group by c.name
;

-- 2. Retrieve the store ID, city, and country for each store.
select store_id, address_id from store;   			
select address_id, address, district, city_id from address;
select country_id, country from country;	
select city_id, city, country_id  from city;

SELECT 
    store_id, city, country
FROM
    store AS s
JOIN address AS a 
ON s.address_id = a.address_id
JOIN city as ci
on a.city_id = ci.city_id
JOIN country as cou
on ci.country_id = cou.country_id
;

-- 3. Calculate the total revenue generated by each store in dollars.
select store_id, count(p.amount) as total_revenue from payment as p
join rental as r
on p.rental_id = r.rental_id
join staff as s
on r.staff_id = s.staff_id
group by store_id
;

-- 4. Determine the average running time of films for each category.

select c.name, avg(length) from film as f
join film_category as fm
ON fm.film_id = f.film_id 
JOIN category as c
on fm.category_id = c.category_id
group by c.name
;

