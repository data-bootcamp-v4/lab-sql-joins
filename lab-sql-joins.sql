-- Challenge 1. List the number of films per category.
SELECT fc.category_id, c.name, COUNT(f.film_id) AS total_films
FROM film AS f
JOIN film_category AS fc
ON f.film_id = fc.film_id
JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name, fc.category_id;

-- Challenge 2. Retrieve the store ID, city, and country for each store.
SELECT s.store_id, ci.city, co.country
FROM store AS s
JOIN address AS a
ON s.address_id = a.address_id
JOIN city AS ci
ON a.city_id = ci.city_id
JOIN country AS co
ON ci.country_id = co.country_id;

-- Challenge 3. Calculate the total revenue generated by each store in dollars.
SELECT s.store_id, 
	SUM(p.amount) AS total_revenue
FROM store AS s
JOIN staff AS st
ON s.store_id = st.store_id
JOIN payment AS p
ON st.staff_id = p.staff_id
GROUP BY s.store_id;

-- Challenge 4. Determine the average running time of films for each category.
SELECT fc.category_id, c.name, AVG(f.length) AS avg_duration
FROM film AS f
JOIN film_category AS fc
ON f.film_id = fc.film_id
JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name, fc.category_id;

-- Challenge 5. Identify the film categories with the longest average running time.
SELECT c.name, AVG(f.length) AS avg_duration
FROM film AS f
JOIN film_category AS fc
ON f.film_id = fc.film_id
JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name, fc.category_id
ORDER BY avg_duration DESC;

-- Challenge 6. Display the top 10 most frequently rented movies in descending order.
SELECT f.title, COUNT(r.rental_id) AS rental_count
FROM film AS f
JOIN inventory AS i 
ON f.film_id = i.film_id
JOIN rental AS r 
ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 10;

-- Challenge 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT f.title,  i.store_id, COUNT(i.inventory_id) AS films_available
FROM film AS f
JOIN inventory AS i 
ON f.film_id = i.film_id
WHERE f.title = 'Academy Dinosaur' AND i.store_id = 1;
  
-- Challenge 8.Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."
SELECT f.title, 
	CASE
		WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
		ELSE 'Not Available'
	END AS availability_check
FROM film AS f 
LEFT JOIN inventory AS i 
ON f.film_id = i.film_id
GROUP BY f.title;
