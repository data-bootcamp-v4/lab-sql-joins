-- Question 1: List the number of films per category

SELECT
    c.name AS category,
    COUNT(f.film_id) AS number_of_films
FROM category AS c
INNER JOIN film_category AS fc
    ON c.category_id = fc.category_id
INNER JOIN film AS f
    ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY c.name ASC;
-- Question 2: Retrieve the store ID, city and country for each store

SELECT
    s.store_id,
    ci.city,
    co.country
FROM store AS s
INNER JOIN address AS a
    ON s.address_id = a.address_id
INNER JOIN city AS ci
    ON a.city_id = ci.city_id
INNER JOIN country AS co
    ON ci.country_id = co.country_id;
    -- Question 3: Calculate the total revenue generated by each store

SELECT
    s.store_id,
    CONCAT('$', ROUND(SUM(p.amount), 2)) AS total_revenue
FROM store AS s
INNER JOIN staff AS st
    ON s.store_id = st.store_id
INNER JOIN payment AS p
    ON st.staff_id = p.staff_id
GROUP BY s.store_id
ORDER BY s.store_id;
-- Question 4: Find the average film running time for each category

SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS average_running_time
FROM category AS c
INNER JOIN film_category AS fc
    ON c.category_id = fc.category_id
INNER JOIN film AS f
    ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY c.name ASC;
-- Bonus Question 5:
-- Rank categories by their average running time

SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS average_running_time
FROM category AS c
INNER JOIN film_category AS fc
    ON c.category_id = fc.category_id
INNER JOIN film AS f
    ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY average_running_time DESC;
-- Bonus Question 6:
-- Display the 10 most frequently rented films

SELECT
    f.title,
    COUNT(r.rental_id) AS rental_count
FROM film AS f
INNER JOIN inventory AS i
    ON f.film_id = i.film_id
INNER JOIN rental AS r
    ON i.inventory_id = r.inventory_id
GROUP BY f.film_id, f.title
ORDER BY rental_count DESC
LIMIT 10;
-- Bonus Question 7:
-- Check whether Academy Dinosaur exists in Store 1's inventory

SELECT
    f.title,
    i.store_id,
    COUNT(i.inventory_id) AS copies_in_inventory,
    CASE
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film AS f
LEFT JOIN inventory AS i
    ON f.film_id = i.film_id
    AND i.store_id = 1
WHERE f.title = 'ACADEMY DINOSAUR'
GROUP BY f.film_id, f.title, i.store_id;
-- Bonus Question 8:
-- Show every film title and its inventory availability

SELECT
    f.title,
    CASE
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film AS f
LEFT JOIN inventory AS i
    ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY f.title ASC;
-- Verify the number of titles that are not in inventory

SELECT
    COUNT(*) AS unavailable_titles
FROM film AS f
LEFT JOIN inventory AS i
    ON f.film_id = i.film_id
WHERE i.inventory_id IS NULL;