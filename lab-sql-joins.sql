USE sakila;

-- List the number of films per category.
SELECT category_id,
       COUNT(film_id) AS film_count
FROM film_category
GROUP BY category_id
ORDER BY film_count DESC;


-- Retrieve the store ID, city, and country for each store.
SELECT 
    store.store_id,
    city.city,
    country.country
FROM store  		-- Every query must have a table to start with, 
					-- and all other tables are joined to that "starting point".
INNER JOIN address -- join each store to its address
    ON store.address_id = address.address_id
INNER JOIN city 
    ON address.city_id = city.city_id
INNER JOIN country 
    ON city.country_id = country.country_id;
    
-- Calculate the total revenue generated by each store in dollars.
SELECT store.store_id,
	SUM(payment.amount) AS total_revenue
FROM payment
INNER JOIN rental
	ON payment.rental_id = rental.rental_id
INNER JOIN inventory
	ON rental.inventory_id = inventory.inventory_id
INNER JOIN store
	ON inventory.store_id = store.store_id
GROUP BY store.store_id;

-- Determine the average running time of films for each category.
SELECT category.`name` AS category_name,
	AVG(film.length) AS mean_length
FROM film  -- contains the length
INNER JOIN film_category  -- links films to categories
	ON film.film_id = film_category.film_id
INNER JOIN category  -- contains the category names
	ON film_category.category_id = category.category_id
GROUP BY category.`name`
ORDER BY category.`name`;

-- Bonus:
-- Identify the film categories with the longest average running time. 
SELECT category.`name` AS category_name,
	AVG(film.length) AS mean_length
FROM film  -- contains the length (Join the tables: film → film_category → category to link each film to its category)
INNER JOIN film_category  -- links films to categories
	ON film.film_id = film_category.film_id
INNER JOIN category  -- contains the category names
	ON film_category.category_id = category.category_id
GROUP BY category.`name`
ORDER BY mean_length DESC
LIMIT 1;

-- Display the top 10 most frequently rented movies in descending order. (join tables: rental -> inventoy -> film)
SELECT film.title,
	COUNT(rental.rental_id) AS rental_count
FROM film
INNER JOIN inventory
	ON film.film_id = inventory.film_id
INNER JOIN rental
	ON inventory.inventory_id = rental.inventory_id
GROUP BY film.title
ORDER BY rental_count DESC
LIMIT 10;

-- Determine if "Academy Dinosaur" can be rented from Store 1.  (join tables: film -> inventoy -> store)
SELECT film.title, store.store_id
FROM film
INNER JOIN inventory
	ON film.film_id = inventory.film_id
INNER JOIN store
	ON inventory.store_id = store.store_id
WHERE film.title = "Academy Dinosaur" AND store.store_id;

-- Provide a list of all distinct film titles, along with their availability status in the inventory.
-- Include a column indicating whether each title is 'Available' or 'NOT available.'
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."
SELECT film.title,
	CASE
		WHEN IFNULL(COUNT(inventory.inventory_id), 0) > 0 THEN 'Available'  -- IFNULL(x, y) returns y if x is NULL
        -- if a film not in the inventory, IFNULL(COUNT(...), 0) ensures the value is 0 instead of NULL.
        ELSE 'Not available'
	END AS availability_status
FROM film
LEFT JOIN inventory
	ON film.film_id = inventory.film_id
GROUP BY film.title
ORDER BY film.title;

-- simplified code: IFNULL(...) is redundant because COUNT() never returns NULL, always returns a number in MySQL
SELECT film.title,  -- title is not aggregated, so must be in GROUP BY
	CASE
		WHEN COUNT(inventory.inventory_id) > 0 THEN 'Available'
        ELSE 'Not available'
	END AS availability_status
FROM film
LEFT JOIN inventory
	ON film.film_id = inventory.film_id
GROUP BY film.title, film.film_id  -- SQL requires that every col in the SELECT list that is not aggregated must appear in the GROUP BY clause.
ORDER BY film.title;
