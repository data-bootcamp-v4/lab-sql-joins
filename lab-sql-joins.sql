-- 1.List the number of films per category.
USE sakila;

SELECT * FROM category;
SELECT * FROM film_category;


SELECT 
	c.category_id,
	c.name,
	COUNT(fc.film_id) AS number_films	
FROM film_category fc
JOIN category c
ON c.category_id=fc.category_id
GROUP BY c.category_id;

-- 2.Retrieve the store ID,city and country for each store

SELECT * FROM store;
SELECT * FROM address;

SELECT 
	s.store_id, 
	s.address_id, 
    c.city_id,
    co.country    
FROM store s
JOIN address a
	ON s.address_id = a.address_id
JOIN city c ON a.city_id=c.city_id
JOIN country co ON c.country_id=co.country_id;

-- 3.Calculate the total revenue generated by each store in dollars.
SELECT 
	sf.store_id,
	SUM(amount) AS total_revenue     
FROM payment p
JOIN staff sf
	ON p.staff_id=sf.staff_id
GROUP BY sf.store_id;

-- 4. Determine the average running time of films for each category

# Every column that is in SELECT that is not an agg function has to be in GROUP BY otherwise it returns an 1055 ERROR

SELECT
    c.name,
    ROUND(AVG(f.length)) AS avg_running_time
FROM film f
JOIN film_category fc
	ON f.film_id = fc.film_id
JOIN category c
	ON fc.category_id=c.category_id
GROUP BY c.category_id, c.name;

-- BONUS: 5. Identify the film categories with the longest average running time.

SELECT
  c.name,
  ROUND(AVG(f.length)) AS avg_running_time
FROM film f
JOIN film_category fc ON f.film_id = fc.film_id
JOIN category c       ON fc.category_id = c.category_id
CROSS JOIN (SELECT AVG(length) AS overall_avg FROM film) g
GROUP BY c.category_id, c.name
HAVING AVG(f.length) > g.overall_avg
ORDER BY avg_running_time DESC
LIMIT 1;

-- BONUS: 6.Display the top 10 most frequently rented movies in descending order.

SELECT 
    f.title,
	COUNT(r.rental_id) as rented_times
FROM rental r
JOIN inventory i
	ON r.inventory_id = i.inventory_id
JOIN film f
	ON i.film_id=f.film_id
GROUP BY f.film_id, f.title
ORDER BY rented_times DESC
LIMIT 10; 

    
	


    
    





    
    