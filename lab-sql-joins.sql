use sakila;

-- -- List the number of films per category.
SELECT COUNT(film_id) as number_of_films, category_id from sakila.film_category
group by category_id;

-- Retrieve the store ID, city, and country for each store.

-- 1-Which tables contain the information that we want? Store, city, country
-- 2-Do they have a common column (content)? last_update
-- 3-Which table will be our "left" table and which one the "right" table Store
-- 4-Determine the type of join. outer
-- 5-Gather everything. Create the join
-- 6-Write the final query.

SELECT 
    s.store_id, 
    c.city, 
    co.country 
FROM 
    sakila.store AS s
JOIN sakila.address AS a ON s.address_id = a.address_id
JOIN sakila.city AS c ON a.city_id = c.city_id
JOIN sakila.country AS co ON c.country_id = co.country_id;


-- Calculate the total revenue generated by each store in dollars.
-- Store + customer + payment
-- Store + customer = store_id ; customer+payment: customer_id
-- payment : payment -customer-store
-- join

SELECT
sum(p.amount) as revenue,
s.store_id as store
from sakila.payment as p
join sakila.customer as c on p.customer_id = c.customer_id
join sakila.store as s on c.store_id = s.store_id
group by store;

-- Determine the average running time of films for each category. 
SELECT
round(avg(l.length),2) as running_time,
f.category_id as category
from sakila.film as l
join sakila.film_category as f on l.film_id = f.film_id
group by category;

-- Identify the film categories with the longest average running time.
SELECT
round(avg(l.length),2) as running_time,
f.category_id as category
from sakila.film as l
join sakila.film_category as f on l.film_id = f.film_id
group by category
order by running_time desc;

-- Display the top 10 most frequently rented movies in descending order. --> rental id, film id, inventorz id
SELECT
count(r.rental_id) as rental,
t.title as film
from sakila.rental as r
join sakila.inventory as i on r.inventory_id = i.inventory_id
join sakila.film as t on i.film_id = t.film_id
group by film
order by rental desc
limit 10;


-- Determine if "Academy Dinosaur" can be rented from Store 1. title (film)--> film_id (film and inventory), store_id (inventory and store)
SELECT
count(a.title) as film,
s.store_id as store
from sakila.film as a
join sakila.inventory as i on a.film_id = i.film_id
join sakila.store as s on i.store_id = s.store_id
WHERE a.title = "Academy Dinosaur"
group by store
;

-- Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement 
-- combined with IFNULL."

SELECT
COUNT(i.film_id) as inventory,
a.title as film,
CASE 
    WHEN COUNT(i.film_id) < '1' THEN 'NOT available'
    WHEN COUNT(i.film_id) is null THEN 'Not in inventory'
    ELSE 'available'
END AS 'Status'
from sakila.inventory as i
join sakila.film as a
on i.film_id = a.film_id
group by film;
