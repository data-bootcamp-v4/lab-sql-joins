-- Write SQL queries to perform the following tasks using the Sakila database:

-- 1.List the number of films per category.
select c.name as category, COUNT(f.film_id) as number_of_films
from category c
join film_category fc 
    on c.category_id = fc.category_id
join film f 
    on fc.film_id = f.film_id
group by c.name
order by number_of_films desc;

-- 2.Retrieve the store ID, city, and country for each store.
select 
	s.store_id, 
	c.city, 
	co.country
from store s
join address a 
	on s.address_id = a.address_id
join city c
	on a.city_id = c.city_id
join country co 
	on c.country_id = co.country_id;

-- 3.Calculate the total revenue generated by each store in dollars.
select 
    s.store_id,
    SUM(p.amount) as total_revenue
from payment p
join rental r 
	on p.rental_id = r.rental_id
join inventory i 
	on r.inventory_id = i.inventory_id
join store s 
	on i.store_id = s.store_id
group by s.store_id
order by total_revenue DESC;


-- 4.Determine the average running time of films for each category.

select 
    c.name as category,
    avg(f.length) as average_running_time
from category c
join film_category fc 
	on c.category_id = fc.category_id
join film f 
	on fc.film_id = f.film_id
group by c.name
order by average_running_time DESC;

-- Bonus:
-- 5.Identify the film categories with the longest average running time.
select 
	c.name as category,
    avg(f.length) as avg_duration
from category c
join film_category fc
	on c.category_id = fc.category_id
join film f
	on fc.film_id = f.film_id
group by category
order by avg_duration desc limit 1 ;

-- 6.Display the top 10 most frequently rented movies in descending order.
select 
	f.title as movie_name,
    count(r.rental_id) as number_of_rentals
from film f
join inventory i
	on f.film_id = i.film_id
join rental r
	on i.inventory_id = r.inventory_id
group by movie_name
order by number_of_rentals desc limit 10;
	
-- 7.Determine if "Academy Dinosaur" can be rented from Store 1.
select 
	f.title as movie_name,
    s.store_id as store
from film f
join inventory i
	on f.film_id = i.film_id
join store s
	on i.store_id = s.store_id
having store = 1 and movie_name like "Academy Dinosaur";



-- 8.Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."
select 
    distinct f.title,
case 
	when i.film_id is null then 'NOT available'
		else 'Available'
    end as availability_status
from film f
left join inventory i
on f.film_id = i.film_id
order by f.title;

