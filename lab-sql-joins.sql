-- Calculate the total revenue generated by each store in dollars.

SELECT staff.store_id AS Store, SUM(payment.amount) AS "Revenue in $"
FROM staff
JOIN payment
ON staff.staff_id = payment.staff_id
GROUP BY staff.store_id;

-- Determine the average running time of films for each category.

select category.name as "Category", ROUND(AVG(film.length), 2) as "Average Running Time"
from category
join film_category
on category.category_id = film_category.category_id
join film
on film_category.film_id = film.film_id
group by category.name;

-- Identify the film categories with the longest average running time.
select category.name as "Category", ROUND(AVG(film.length), 2) as "Average Running Time"
from category
join film_category
on category.category_id = film_category.category_id
join film
on film_category.film_id = film.film_id
group by category.name order by ROUND(AVG(film.length), 2) DESC LIMIT 3;