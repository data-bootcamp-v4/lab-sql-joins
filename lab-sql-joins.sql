# 5. Identify the film categories with the longest average running time.
SELECT  c.`name` AS Category,
		ROUND(AVG(f.length)) AS 'Average running time (min)'
FROM film_category AS fc
INNER JOIN film AS f
	ON f.film_id = fc.film_id
INNER JOIN category AS c
	ON c.category_id = fc.category_id
GROUP BY c.`name`
ORDER BY AVG(f.length) DESC
LIMIT 5;

# 6. Display the top 10 most frequently rented movies in descending order.
SELECT  f.title AS Movie_title,
		COUNT(r.rental_id) AS Times_rented
FROM inventory AS i
LEFT JOIN rental AS r
	ON i.inventory_id = r.inventory_id
LEFT JOIN film AS f
	ON f.film_id = i.film_id
GROUP BY f.title
ORDER BY TImes_rented DESC
LIMIT 10;

# 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT  s.store_id,
		f.title,
        COUNT(*) AS Stock
FROM inventory AS i
INNER JOIN store AS s
	ON i.store_id = s.store_id
INNER JOIN film AS f
	ON f.film_id = i.film_id
WHERE f.title LIKE 'Academy Dinosaur'
	AND s.store_id = 1
GROUP BY f.title, s.store_id;

# 8. Provide a list of all distinct film titles, along with their availability status in the inventory.
#    Include a column indicating whether each title is 'Available' or 'NOT available.' Note that there are 42
#    titles that are not in the inventory, and this information can be obtained using a CASE statement combined
#    with IFNULL."
SELECT f.title AS Title,
		CASE
			WHEN i.inventory_id IS NULL THEN 'NOT available'
            ELSE 'Available'
		END AS Availability
FROM film AS f
LEFT JOIN inventory AS i 
    ON f.film_id = i.film_id
GROUP BY f.title, availability;

