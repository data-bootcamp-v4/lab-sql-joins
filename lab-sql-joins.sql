#Write SQL queries to perform the following tasks using the Sakila database:
#1.List the number of films per category.
#--------------------------------------------MY_ANSWER--------------------------------------------#
SELECT category.category_id, COUNT(film_id)
FROM category
INNER JOIN film_category 
USING(category_id);
#--------------------------------------------SOLUTION--------------------------------------------#
SELECT category.name, COUNT(film_category.film_id) AS num_films
FROM category
INNER JOIN film_category ON category.category_id = film_category.category_id
GROUP BY category.name
ORDER BY num_films DESC;

#2.Retrieve the store ID, city, and country for each store.
#--------------------------------------------MY_ANSWER--------------------------------------------#
SELECT country.country,city.city,customer.store_id
FROM country
INNER JOIN city USING(country_id)
INNER JOIN address USING(city_id)
INNER JOIN customer USING(address_id);


#3.Calculate the total revenue generated by each store in dollars.
#--------------------------------------------MY_ANSWER--------------------------------------------#
SELECT SUM(payment.amount),store.store_id
FROM store
INNER JOIN customer USING(store_id)
INNER JOIN  payment USING(customer_id);
#--------------------------------------------SOLUTION--------------------------------------------#
SELECT SUM(payment.amount),store.store_id
FROM store
INNER JOIN customer USING(store_id)
INNER JOIN  payment USING(customer_id)
GROUP BY store.store_id;



#4.Determine the average running time of films for each category.
#--------------------------------------------MY_ANSWER--------------------------------------------#
SELECT category.name,AVG(film.length) AS Average_runtime
FROM category
INNER JOIN film_category USING(category_id)
INNER JOIN film USING(film_id)
GROUP BY category.name
ORDER BY Average_runtime;


