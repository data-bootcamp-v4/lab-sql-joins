-- 1. List the number of films per category.
SELECT c.name as category_name, COUNT(f.film_id) as count_of_films
FROM sakila.category as c JOIN sakila.film_category as fc
ON c.category_id = fc.category_id
JOIN sakila.film as f
ON fc.film_id = f.film_id
GROUP BY category_name;

-- 2. Retrieve the store ID, city, and country for each store.
SELECT s.store_id, ci.city, co.country
FROM sakila.store as s JOIN sakila.address as a
ON s.address_id = a.address_id
JOIN sakila.city as ci
ON a.city_id = ci.city_id
JOIN sakila.country as co
ON ci.country_id = co.country_id
WHERE ci.country_id IS NOT NULL AND co.country_id 
AND s.address_id IS NOT NULL AND a.address_id IS NOT NULL;


-- 3. Calculate the total revenue generated by each store in dollars.
SELECT st.store_id, COUNT(pa.amount) as 'amount, $'
FROM sakila.payment as pa JOIN sakila.customer as cu
ON pa.customer_id = cu.customer_id
JOIN sakila.store as st
ON cu.store_id = st.store_id
GROUP BY store_id;

-- 4. Determine the average running time of films for each category
SELECT c.name as category_name, AVG(f.length) as avg_running_time
FROM sakila.category as c JOIN sakila.film_category as fc
ON c.category_id = fc.category_id
JOIN sakila.film as f
ON fc.film_id = f.film_id
GROUP BY category_name
ORDER BY category_name;

-- 5. Identify the film categories with the longest average running time.
SELECT c.name as category_name, AVG(f.length) as avg_running_time
FROM sakila.category as c JOIN sakila.film_category as fc
ON c.category_id = fc.category_id
JOIN sakila.film as f
ON fc.film_id = f.film_id
GROUP BY category_name
HAVING avg_running_time > 115
ORDER BY avg_running_time DESC;

-- 6. Display the top 10 most frequently rented movies in descending order.
SELECT f.title, COUNT(r.inventory_id) as count
FROM sakila.rental as r JOIN sakila.inventory as i
ON r.inventory_id = i.inventory_id
JOIN sakila.film as f
ON i.film_id = f.film_id
GROUP BY f.title
ORDER BY count DESC
LIMIT 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT i.store_id, f.title
FROM sakila.inventory as i JOIN sakila.film as f
ON i.film_id = f.film_id
WHERE f.title = "Academy Dinosaur"
GROUP BY i.store_id;

-- 8. Provide a list of all distinct film titles, along with their availability 
-- status in the inventory. Include a column indicating whether each title is 'Available' 
-- or 'NOT available.' Note that there are 42 titles that are not in the inventory, 
-- and this information can be obtained using a CASE statement combined with IFNULL."
SELECT DISTINCT f.title,
CASE 
    WHEN IFNULL(i.inventory_id, 0) THEN 'Not avaliable'
    ELSE 'Not avaliable'
END AS 'Avaliability'
FROM sakila.film as f 
JOIN sakila.inventory as i
ON f.film_id = i.film_id
ORDER BY f.title;
