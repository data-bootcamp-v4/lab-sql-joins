USE sakila;

-- Write SQL queries to perform the following tasks using the Sakila database:

-- List the number of films per category.
SELECT name, count(*) AS number_of_films
FROM film_category fc
INNER JOIN category c
ON c.category_id = fc.category_id
JOIN film f
ON fc.film_id = f.film_id
GROUP BY name
ORDER BY number_of_films DESC;

-- Retrieve the store ID, city, and country for each store.
SELECT store_id, city, country
FROM country co
JOIN city ci
ON co.country_id = ci.country_id
JOIN address ad
ON ad.city_id = ci.city_id
JOIN store s
ON ad.address_id = s.address_id;

-- Calculate the total revenue generated by each store in dollars.
SELECT store_id, SUM(amount) AS total_sales
FROM payment p
JOIN staff_list sl
ON p.staff_id = sl.SID
JOIN store s
ON s.manager_staff_id = sl.SID
GROUP BY store_id;

-- Determine the average running time of films for each category.
SELECT name, ROUND(AVG(length),2) AS average_running_time
FROM film_category fc
INNER JOIN category c
ON c.category_id = fc.category_id
JOIN film f
ON fc.film_id = f.film_id
GROUP BY name;

-- Bonus:

-- Identify the film categories with the longest average running time.
SELECT name, AVG(length) AS average_running_time
FROM film_category fc
INNER JOIN category c
ON c.category_id = fc.category_id
JOIN film f
ON fc.film_id = f.film_id
GROUP BY name
ORDER BY average_running_time DESC
LIMIT 1;

-- Display the top 10 most frequently rented movies in descending order.
SELECT title, COUNT(inv.film_id) AS number_of_rentals
FROM inventory inv
JOIN film f
ON inv.film_id = f.film_id
GROUP BY title
ORDER BY number_of_rentals DESC
LIMIT 10;

