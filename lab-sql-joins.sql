/* Write SQL queries to perform the following tasks using the Sakila database:*/
USE sakila;

/* 1. List the number of films per category.*/
SELECT * FROM film;
SELECT * FROM category;
SELECT * FROM film_category;

SELECT c.category_id, c.name, count(*) as films_by_category
FROM film f
JOIN film_category fc
ON f.film_id = fc.film_id
JOIN category c 
ON fc.category_id = c.category_id
GROUP BY c.category_id
ORDER BY films_by_category DESC;

/* 2. Retrieve the store ID, city, and country for each store.*/
SELECT * FROM store;
SELECT * FROM address;
SELECT * FROM city;
SELECT * FROM country;

SELECT s.store_id, city, country
FROM store s
JOIN address a
ON s.address_id = a.address_id
JOIN city c
ON a.city_id = c.city_id
JOIN country ct
ON c.country_id = ct.country_id;

/* 3. Calculate the total revenue generated by each store in dollars.*/
SELECT * FROM store;
SELECT * FROM staff;
SELECT * FROM payment;

SELECT s.store_id, sum(amount) AS total_revenue
FROM store s
JOIN staff f
ON s.store_id = f.store_id
JOIN payment p
ON f.staff_id = p.staff_id
GROUP BY s.store_id;

/* 4. Determine the average running time of films for each category.*/
SELECT c.category_id, c.name, ROUND(AVG(f.length),2) AS avg_length
FROM film f
JOIN film_category fc
ON f.film_id = fc.film_id
JOIN category c 
ON fc.category_id = c.category_id
GROUP BY c.category_id;

/* Bonus:
5. Identify the film categories with the longest average running time.*/
SELECT c.category_id, c.name, ROUND(AVG(f.length),2) AS avg_length
FROM film f
JOIN film_category fc
ON f.film_id = fc.film_id
JOIN category c 
ON fc.category_id = c.category_id
GROUP BY c.category_id
ORDER BY avg_length DESC;

/* 6. Display the top 10 most frequently rented movies in descending order.*/
SELECT f.film_id, f.title, count(*) AS most_rented
FROM rental r
JOIN inventory i
ON r.inventory_id = i.inventory_id
JOIN film f
ON i.film_id = f.film_id
GROUP BY f.film_id
ORDER BY most_rented DESC
LIMIT 10;

/* 7. Determine if "Academy Dinosaur" can be rented from Store 1.*/
SELECT * FROM inventory;
SELECT * FROM film;

SELECT f.title, i.store_id, count(i.inventory_id) AS copies
FROM film f
JOIN inventory i
ON f.film_id = i.film_id
WHERE f.title = "Academy Dinosaur" AND i.store_id = 1
GROUP BY f.title;

/* 8. Provide a list of all distinct film titles, along with their availability status in the inventory. 
Include a column indicating whether each title is 'Available' or 'NOT available.' Note that there are 42 titles that are not in the 
inventory, and this information can be obtained using a CASE statement combined with IFNULL."*/

SELECT f.title, count(i.inventory_id) AS copies,
CASE 
	WHEN count(i.inventory_id) > 0 THEN "Available" 
	ELSE "NOT Available" 
	END AS inventory_status
FROM film f
LEFT JOIN inventory i
ON f.film_id = i.film_id
GROUP BY f.title;