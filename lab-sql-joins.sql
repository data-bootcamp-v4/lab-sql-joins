-- 1. List the number of films per category
SELECT COUNT(film.film_id) AS number_of_films, category.name AS category_name
FROM category 
LEFT JOIN film_category ON category.category_id = film_category.category_id
LEFT JOIN film ON film.film_id = film_category.film_id
GROUP BY category.name, category.category_id;
-- 2. Retrieve the store ID, city, and country for each store.
SELECT store.store_id, city.city, country.country
FROM store  
LEFT JOIN address ON store.store_id = address.address_id
LEFT JOIN city ON city.city_id = address.city_id
LEFT JOIN country ON country.country_id = city.country_id;
-- 3. Calculate the total revenue generated by each store in dollars.
SELECT store.store_id, SUM(payment.amount) AS revenue_in_dollars
FROM store 
LEFT JOIN staff ON staff.store_id = store.store_id
LEFT JOIN payment ON staff.staff_id = payment.staff_id
GROUP BY store.store_id;
-- 4. Determine the average running time of films for each category.
SELECT AVG(film.length) AS average_runing_time, category.name AS category
FROM film 
LEFT JOIN film_category ON film_category.film_id = film.film_id
LEFT JOIN category ON category.category_id = film_category.category_id
GROUP BY category.name;