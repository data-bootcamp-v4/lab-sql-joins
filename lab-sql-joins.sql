-- 1 List the number of films per category.
SELECT * from sakila.category
SELECT * from sakila.film_category

SELECT 
    c.name AS category_name,
    COUNT(fc.film_id) AS num_films
FROM sakila.category AS c
JOIN sakila.film_category AS fc
ON c.category_id = fc.category_id
GROUP BY c.category_id, c.name
ORDER BY num_films DESC;

-- 3 Retrieve the store ID, city, and country for each store.
SELECT*FROM sakila.city -- city , city_id, country_id
SELECT*FROM sakila.store -- store_id, address_id
SELECT*FROM sakila.country -- country_id, country
SELECT*FROM sakila.address --  address_id, district, city_id, portal_code, location


SELECT 
    s.store_id,
    ci.city,
    co.country
FROM sakila.store AS s
JOIN sakila.address AS a
    ON s.address_id = a.address_id
JOIN sakila.city AS ci
    ON a.city_id = ci.city_id
JOIN sakila.country AS co
    ON ci.country_id = co.country_id;

-- 3 Calculate the total revenue generated by each store in dollars.
SELECT*FROM sakila.store -- store_id, address_id
SELECT*FROM sakila.payment -- staff_id , amount
SELECT*FROM sakila.staff -- staff_id, store_id, address_id

SELECT 
    SUM(p.amount),
    sto.store_id
FROM sakila.staff AS sta
JOIN sakila.payment AS p
    ON sta.staff_id = p.staff_id
JOIN sakila.store AS sto
	ON sta.store_id = sto.store_id
GROUP BY sto.store_id

-- Determine the average running time of films for each category.
SELECT * FROM sakila.film_category -- film_id, category_id
SELECT * FROM sakila.film -- film_id, length

SELECT 
    b.category_id, 
    AVG(a.length) AS avg_length
FROM sakila.film AS a
JOIN sakila.film_category AS b
    ON a.film_id = b.film_id
GROUP BY b.category_id;

-- 5 Identify the film categories with the longest average running time.
SELECT 
    b.category_id, 
    AVG(a.length) AS avg_length
FROM sakila.film AS a
JOIN sakila.film_category AS b
    ON a.film_id = b.film_id
GROUP BY b.category_id
ORDER BY avg_length DESC;

-- 6 Display the top 10 most frequently rented movies in descending order.
SELECT 
    f.title,
    COUNT(r.rental_id) AS rental_count
FROM sakila.rental AS r
JOIN sakila.inventory AS i
    ON r.inventory_id = i.inventory_id
JOIN sakila.film AS f
    ON i.film_id = f.film_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 10;

-- 7 Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT 
    f.title,
    i.store_id,
    COUNT(i.inventory_id) AS copies_available
FROM sakila.film AS f
JOIN sakila.inventory AS i
    ON f.film_id = i.film_id
WHERE f.title = 'Academy Dinosaur'
  AND i.store_id = 1
GROUP BY f.title, i.store_id;
 