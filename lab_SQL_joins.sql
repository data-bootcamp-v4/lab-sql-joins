-- Write SQL queries to perform the following tasks using the Sakila database:
use sakila;
-- 1. List the number of films per category.
select sc.name, count(sf.film_id) as film_count from sakila.film as sf
inner join sakila.film_category as sfc
	on sf.film_id = sfc.film_id
inner join sakila.category as sc
	on sfc.category_id = sc.category_id
group by sc.name
order by film_count desc;

-- 2. Retrieve the store ID, city, and country for each store.
select store_id, sc.city, c.country from sakila.store as ss
join sakila.address as sa
	on ss.address_id = sa.address_id
join sakila.city as sc
	on sa.city_id = sc.city_id
join sakila.country as c
	on sc.country_id = c.country_id
;

-- 3. Calculate the total revenue generated by each store in dollars.
select store.store_id, sum(amount) from payment
	inner join staff
		on payment.staff_id = staff.staff_id
    inner join store
		on staff.store_id = store.store_id
    group by store.store_id
    ;

-- 4. Determine the average running time of films for each category.
select category.name, avg(length) as Avg_length from film
inner join film_category
	on film.film_id = film_category.film_id
inner join category
	on film_category.category_id = category.category_id
group by category.name;

-- BONUS
-- Identify the film categories with the longest average running time.
select category.name, avg(length) from film
inner join film_category
	on film.film_id= film_category.film_id
inner join category
	on film_category.category_id  = category.category_id 
group by category.name
order by avg(length) desc;
-- Display the top 10 most frequently rented movies in descending order.
select title, count(rental.inventory_id) as number_of_times_rented from film
inner join inventory
	on film.film_id = inventory.film_id
inner join rental
	on inventory.inventory_id = rental.inventory_id
group by title
order by count(rental.inventory_id) desc
limit 10;
