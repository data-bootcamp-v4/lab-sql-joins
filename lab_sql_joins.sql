-- Write SQL queries to perform the following tasks using the Sakila database:
-- 1. List the number of films per category.
SELECT cat.name cat_name, COUNT(*) films_by_category
FROM film f
INNER JOIN film_category c
ON f.film_id = c.film_id
INNER JOIN category cat
ON c.category_id = cat.category_id
GROUP BY c.category_id;

-- 2. Retrieve the store ID, city, and country for each store.
SELECT s.store_id, c.city, co.country
FROM store s
INNER JOIN address a
ON s.address_id = a.address_id
INNER JOIN city c
ON a.city_id = c.city_id
INNER JOIN country co
ON c.country_id = co.country_id;

-- 3. Calculate the total revenue generated by each store in dollars.
SELECT sto.store_id, SUM(amount) total_revenue
FROM store sto
INNER JOIN staff sta
ON sto.store_id = sta.store_id
INNER JOIN payment p
ON sta.staff_id = p.staff_id
GROUP BY sto.store_id;

-- 4. Determine the average running time of films for each category.
SELECT cat.name cat_name, sec_to_time(ROUND(AVG(f.length), 2)*60) avg_running_time_per_cat
FROM film f
INNER JOIN film_category c
ON f.film_id = c.film_id
INNER JOIN category cat
ON c.category_id = cat.category_id
GROUP BY c.category_id;

-- Bonus:
-- 5. Identify the film categories with the longest average running time.
SELECT cat.name cat_name, sec_to_time(ROUND(AVG(f.length), 2)*60) avg_running_time_per_cat
FROM film f
INNER JOIN film_category c
ON f.film_id = c.film_id
INNER JOIN category cat
ON c.category_id = cat.category_id
GROUP BY c.category_id
ORDER BY avg_running_time_per_cat DESC
LIMIT 1;

