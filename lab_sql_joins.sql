SELECT
	c.name,
	ROUND(AVG(f.length), 0) as avg_length
FROM category AS c
LEFT JOIN film_category AS fc
	ON c.category_id = fc.category_id
LEFT JOIN film AS f
	ON fc.film_id = f.film_id
GROUP BY
	c.name
ORDER BY
	avg_length DESC LIMIT 5;



-- ==========================================================
-- 6) Display the top 10 most frequently rented movies in descending order.
-- TODO:

SELECT
	f.title,
    COUNT(r.rental_id) as freq_rented
FROM film AS f
JOIN inventory AS i
	ON f.film_id = i.film_id
JOIN rental AS r
	ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY freq_rented DESC 
LIMIT 10;


-- ==========================================================
-- 7) Determine if "Academy Dinosaur" can be rented from Store 1.
-- TODO:

SELECT
	DISTINCT f.title
FROM film AS f
JOIN inventory AS i
	ON f.film_id = i.film_id
JOIN store AS s
	ON i.store_id = s.store_id
WHERE
	f.title = 'Academy Dinosaur' AND s.store_id = 1;


-- ==========================================================
-- 8) Distinct film titles + availability status ('Available' / 'NOT available')
-- Hint: `CASE` + `IFNULL`
-- TODO:
SELECT
	f.title,
	CASE
		WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
		ELSE 'NOT available'
	END AS availability_status
FROM film AS f
LEFT JOIN inventory AS i
	ON f.film_id = i.film_id
GROUP BY
	f.film_id,
	f.title;









