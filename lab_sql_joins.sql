use sakila;

-- Write SQL queries to perform the following tasks using the Sakila database:
-- 1. List the number of films per category.

select c.name as category_name, count(f.film_id) as film_count
from sakila.film f
join sakila.film_category fc on f.film_id = fc.film_id
join sakila.category c on fc.category_id = c.category_id
group by c.name
order by film_count desc;
 
-- 2. Retrieve the store ID, city, and country for each store.
select s.store_id, ci.city, co.country
from sakila.store s
join sakila.address a on s.address_id = a.address_id
join sakila.city ci on a.city_id = ci.city_id
join sakila.country co on ci.country_id = co.country_id;

-- 3. Calculate the total revenue generated by each store in dollars.

select s.store_id, round(sum(p.amount), 2) * 1 as total_revenue_in_usd 
from sakila.payment p
join sakila.customer cu on p.customer_id = cu.customer_id
join sakila.store s on cu.store_id = s.store_id
group by s.store_id;
    
-- 4. Determine the average running time of films for each category.

select fc.category_id, avg(f.length) as average_length
from sakila.film f 
join sakila.film_category fc on f.film_id = fc.film_id
group by fc.category_id;

-- Bonus:
-- 5. Identify the film categories with the longest average running time.

select fc.category_id, avg(f.length) as longest_average
from sakila.film f
join sakila.film_category fc on f.film_id = fc.film_id
group by fc.category_id
order by longest_average desc;

-- 6. Display the top 10 most frequently rented movies in descending order.

select f.title, count(r.rental_id) as frequently_rented
from sakila.rental r
join sakila.inventory i on i.inventory_id = r.inventory_id
join sakila.film f on f.film_id = i.film_id
group by f.title
order by frequently_rented desc
limit 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.

select f.title, s.store_id, count(i.inventory_id) as copies_avaible
from sakila.film f
join sakila.inventory i on f.film_id = i.film_id
join sakila.store s on i.store_id = s.store_id
where f.title = 'Academy Dinosaur' and s.store_id = 1
group by f.title, store_id;

-- 8.Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' Note that there are 42 titles 
-- that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."

select f.title, 
case
	when count(i.inventory_id) > 0 then 'Available'
    else 'not available'
end as availability_check
from sakila.film f 
left join sakila.inventory i on f.film_id = i.film_id
group by f.title;






