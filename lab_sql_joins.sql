USE sakila;

-- Write SQL queries to perform the following tasks using the Sakila database:
-- 1. List the number of films per category.

SELECT * FROM category;
SELECT * FROM film_category;

SELECT c.name, 
	COUNT(fc.film_id) AS number_of_films
FROM category AS c
JOIN film_category AS fc 
ON c.category_id = fc.category_id
GROUP BY c.name;

-- 2. Retrieve the store ID, city, and country for each store.

SELECT * FROM store;
SELECT * FROM address;
SELECT * FROM city;
SELECT * FROM country;

SELECT s.store_ID, c.city, co.country
FROM store AS s
JOIN address AS a
ON s.address_id = a.address_id
JOIN city AS c
ON a.city_id = c.city_id
JOIN country AS co
ON c.country_id = co.country_id
GROUP BY store_ID;

-- 3. Calculate the total revenue generated by each store in dollars.

SELECT * FROM payment;
SELECT * FROM staff;

SELECT s.store_id, SUM(p.amount) AS "revenue U$"
FROM staff AS s
JOIN payment AS p
ON p.staff_id = s.staff_id
GROUP BY s.store_id;

-- 4. Determine the average running time of films for each category.

SELECT * FROM film_category;
SELECT * FROM category;
SELECT * FROM film;

SELECT c.name, AVG(f.length) AS running_time
FROM category AS c
JOIN film_category AS fc
ON c.category_id = fc.category_id
JOIN film AS f
ON f.film_id = fc.film_id
GROUP BY c.name;

-- Bonus:

-- Identify the film categories with the longest average running time.

SELECT c.name, AVG(f.length) AS running_time
FROM category AS c
JOIN film_category AS fc
ON c.category_id = fc.category_id
JOIN film AS f
ON f.film_id = fc.film_id
GROUP BY c.name
ORDER BY AVG(f.length) DESC;

-- Display the top 10 most frequently rented movies in descending order.

SELECT * FROM rental;
SELECT * FROM film;
SELECT * FROM inventory;

SELECT f.title, COUNT(r.rental_id) AS rented_quantity
FROM film AS f
JOIN inventory AS i
	ON f.film_id = i.film_id
JOIN rental AS r
	ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rented_quantity DESC
LIMIT 10;

-- Determine if "Academy Dinosaur" can be rented from Store 1.

SELECT * FROM film;
SELECT * FROM inventory;

SELECT f.title, i.store_id
FROM film AS f 
JOIN inventory AS i
ON f.film_id = i.film_id
WHERE title = "Academy Dinosaur" AND i.store_id = 1;

-- Provide a list of all distinct film titles, along with their availability status in the inventory. Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."

SELECT * FROM film;
SELECT * FROM inventory;

SELECT DISTINCT f.title,
CASE
    WHEN IFNULL(i.inventory_id, 0) = 0 THEN 'NOT available'
    ELSE 'Available'
END AS availability_status
FROM film AS f
JOIN inventory AS i
ON f.film_id = i.film_id
ORDER BY f.title;


