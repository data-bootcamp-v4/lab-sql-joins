-- 1) List the number of films per category.
-- TODO:
-- 
SELECT
	c.name,
	COUNT(DISTINCT fc.film_id) as num_films
FROM category as c
LEFT JOIN film_category as fc 
	ON c.category_id = fc.category_id
GROUP BY c.name
ORDER BY num_films DESC;

-- ==========================================================
-- 2) Retrieve the store ID, city, and country for each store.
-- TODO:

SELECT
	store.store_id,
	city.city,
	country.country
FROM store as store
LEFT JOIN address as address
	ON store.address_id = address.address_id
LEFT JOIN city as city
	ON city.city_id = address.city_id
LEFT JOIN country as country
	ON city.country_id = country.country_id;


-- ==========================================================
-- 3) Calculate the total revenue generated by each store in dollars.
-- TODO:

SELECT
	store.store_id,
	SUM(payment.amount) AS total_revenue
FROM store AS store
LEFT JOIN staff AS staff
	ON store.store_id = staff.store_id
LEFT JOIN payment AS payment
	ON staff.staff_id = payment.staff_id
GROUP BY
	store.store_id;


-- ==========================================================
-- 4) Determine the average running time of films for each category.
-- TODO:

SELECT
	c.name,
	ROUND(AVG(f.length), 0) as avg_length
FROM category AS c
LEFT JOIN film_category AS fc
	ON c.category_id = fc.category_id
LEFT JOIN film AS f
	ON fc.film_id = f.film_id
GROUP BY
	c.name
ORDER BY
	avg_length DESC;


-- ==========================================================
