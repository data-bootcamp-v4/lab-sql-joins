-- Write SQL queries to perform the following tasks using the Sakila database:

USE sakila;

-- 1. List the number of films per category.
SELECT COUNT(f.film_id), c.name
FROM film_category f
JOIN category c
ON f.category_id = c.category_id
GROUP BY c.name;

