Use sakila;
#1. List the number of films per category.
SELECT c.name, cid.number_of_films
FROM category as c
JOIN (SELECT category_id, COUNT(*)  AS number_of_films
	FROM film_category
	GROUP BY category_id) as cid
ON c.category_id = cid.category_id;

#2. Retrieve the store ID, city, and country for each store.
SELECT st_c.store_id, st_c.city, co.country
FROM country AS co
JOIN (SELECT c.city, c.country_id, store_id
	FROM city AS c
	JOIN (SELECT a.address_id, a.city_id, s.store_id
			FROM address AS a
			JOIN (SELECT store_id, address_id FROM store) AS s
			ON a.address_id = s.address_id) AS st_ad
	ON c.city_id = st_ad.city_id) AS st_c
ON co.country_id = st_c.country_id;

#3. Calculate the total revenue generated by each store in dollars.
SELECT s.store_id, p.total_revenue
FROM staff AS s
JOIN (SELECT staff_id, SUM(amount) AS total_revenue
		FROM payment
		GROUP BY staff_id) AS p
ON s.staff_id = p.staff_id;

#4.  Determine the average running time of films for each category.
SELECT c_id.name AS category, AVG(f.length)
FROM film AS f
JOIN(SELECT c.name, c.category_id, cid.film_id
	FROM category as c
	JOIN (SELECT film_id, category_id
		FROM film_category) as cid
	ON c.category_id = cid.category_id) AS c_id
ON f.film_id = c_id.film_id
GROUP BY category;