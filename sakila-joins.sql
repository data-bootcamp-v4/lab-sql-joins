USE sakila;

-- 1. List the number of films per category.(film, film_category, category) 

SELECT category.name AS category_name, COUNT(film.film_id) AS num_films
FROM  sakila.category
JOIN  sakila.film_category ON category.category_id = film_category.category_id
JOIN  sakila.film ON film_category.film_id = film.film_id
GROUP BY category.name;

-- 2. Retrieve the store ID, city, and country for each store.
SELECT COUNT(distinct store_id) FROM store;

SELECT 
    s.store_id, 
    c.city,
    co.country  
FROM sakila.store s
JOIN sakila.address a ON s.address_id = a.address_id
JOIN sakila.city c ON a.city_id = c.city_id
JOIN sakila.country co ON c.country_id = co.country_id;
    
-- 3. Calculate the total revenue generated by each store in dollars.
SELECT st.store_id AS StoreId, SUM(p.amount) AS total_revenue
FROM sakila.store st
JOIN sakila.staff s ON st.store_id = s.store_id
JOIN sakila.payment p ON s.staff_id = p.staff_id
GROUP BY st.store_id;

-- 4. Determine the average running time of films for each category.
SELECT fc.category_id, ROUND(AVG(f.length),1) AS avg_length
FROM film_category AS fc
JOIN film AS f
ON fc.film_id = f.film_id
GROUP BY fc.category_id;

