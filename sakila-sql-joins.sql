# 1. List the number of films per category.
SELECT
  c.name AS category,
  COUNT(*) AS film_count
FROM category c
JOIN film_category fc ON fc.category_id = c.category_id
GROUP BY c.category_id, c.name
ORDER BY film_count DESC, category ASC;

# 2. Retrieve the store ID, city, and country for each store.
# join  tables city and country on country_id, then join address on city_id, and then join store on address_id
# or vice versa, join address to store on adress_id, then join city on city_id, then join country on country_id
SELECT
  s.store_id,
  ci.city,
  co.country
FROM store s
JOIN address a ON a.address_id = s.address_id
JOIN city ci   ON ci.city_id = a.city_id
JOIN country co ON co.country_id = ci.country_id
ORDER BY s.store_id;

# Calculate the total revenue generated by each store in dollars.
# we need to join staff to store on store_id, and then join payment on staff_id
SELECT
  s.store_id,
  SUM(p.amount) AS total_revenue
FROM store s
JOIN staff st   ON st.store_id = s.store_id
JOIN payment p  ON p.staff_id = st.staff_id
GROUP BY s.store_id
ORDER BY total_revenue DESC;

# 4. Determine the average running time of films for each category.
# get film table
# use function for average length of movie
# join film_category on film_id
# join category table  on category_id, category_id
# group by c.name
SELECT
  c.name AS category,
  ROUND(AVG(f.length), 2) AS average_running_time
FROM category c
JOIN film_category fc ON fc.category_id = c.category_id
JOIN film f           ON f.film_id = fc.film_id
GROUP BY c.name
ORDER BY average_running_time DESC;

# 5. Identify the film categories with the longest average running time.
# just adding LIMIT 1 to our previous code.
SELECT
  c.name AS category,
  ROUND(AVG(f.length), 2) AS avg_running_time
FROM category c
JOIN film_category fc ON fc.category_id = c.category_id
JOIN film f           ON f.film_id = fc.film_id
GROUP BY c.name
ORDER BY avg_running_time DESC
LIMIT 1;

# 6. Display the top 10 most frequently rented movies in descending order.
# join inventory to film on film_id, then join rental on inventory_id
SELECT
  f.film_id,
  f.title,
  COUNT(*) AS rental_count
FROM rental r
JOIN inventory i ON i.inventory_id = r.inventory_id
JOIN film f      ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY rental_count DESC
LIMIT 10;

# 7. Determine if "Academy Dinosaur" can be rented from Store 1.
SELECT
  i.store_id,
  f.title,
  COUNT(*) AS total_copies,
  SUM(CASE WHEN r.rental_id IS NULL THEN 1 ELSE 0 END) AS available_copies
FROM film f
JOIN inventory i ON i.film_id = f.film_id
LEFT JOIN rental r
  ON r.inventory_id = i.inventory_id
 AND r.return_date IS NULL
WHERE f.title = 'ACADEMY DINOSAUR'
  AND i.store_id = 1
GROUP BY i.store_id, f.title;

# 8. Provide a list of all distinct film titles, along with their availability status in the inventory. 
# Include a column indicating whether each title is 'Available' or 'NOT available.' 
# Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."
SELECT
  f.title,
  CASE
    WHEN IFNULL(inv.copies, 0) > 0 THEN 'Available'
    ELSE 'NOT available'
  END AS availability_status
FROM film f
LEFT JOIN (
  SELECT film_id, COUNT(*) AS copies
  FROM inventory
  GROUP BY film_id
) inv ON inv.film_id = f.film_id
ORDER BY f.title;
