USE sakila;

-- Write SQL queries to perform the following tasks using the Sakila database:

-- List the number of films per category.

SELECT 
    c.name AS category_name,
    COUNT(fc.film_id) AS film_count
FROM 
    film_category AS fc
JOIN 
    category AS c 
    ON fc.category_id = c.category_id
GROUP BY 
    c.name
ORDER BY 
    film_count DESC;

-- Retrieve the store ID, city, and country for each store.

SELECT 
    s.store_id,
    ci.city,
    co.country
FROM 
    store AS s
JOIN 
    address AS a ON s.address_id = a.address_id
JOIN 
    city AS ci ON a.city_id = ci.city_id
JOIN 
    country AS co ON ci.country_id = co.country_id
ORDER BY 
    s.store_id;

-- Calculate the total revenue generated by each store in dollars.

SELECT 
    s.store_id,
    SUM(p.amount) AS total_revenue
FROM 
    payment AS p
JOIN 
    staff AS st ON p.staff_id = st.staff_id
JOIN 
    store AS s ON st.store_id = s.store_id
GROUP BY 
    s.store_id
ORDER BY 
    total_revenue DESC;

-- Determine the average running time of films for each category.

SELECT 
    c.name AS category_name,
    ROUND(AVG(f.length), 2) AS average_running_time
FROM 
    film AS f
JOIN 
    film_category AS fc ON f.film_id = fc.film_id
JOIN 
    category AS c ON fc.category_id = c.category_id
GROUP BY 
    c.name
ORDER BY 
    average_running_time DESC;

-- Bonus:

-- Identify the film categories with the longest average running time.

SELECT 
    c.name AS category_name,
    ROUND(AVG(f.length), 2) AS average_running_time
FROM 
    film AS f
JOIN 
    film_category AS fc ON f.film_id = fc.film_id
JOIN 
    category AS c ON fc.category_id = c.category_id
GROUP BY 
    c.name
ORDER BY 
    average_running_time DESC
LIMIT 5;

-- Display the top 10 most frequently rented movies in descending order.

SELECT f.title,
       COUNT(r.rental_id) AS rental_count
FROM film f
JOIN inventory i ON f.film_id = i.film_id
JOIN rental r ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 10;

-- Determine if "Academy Dinosaur" can be rented from Store 1.

SELECT f.title,
       s.store_id,
       CASE
           WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
           ELSE 'NOT Available'
       END AS availability
FROM film f
LEFT JOIN inventory i ON f.film_id = i.film_id AND i.store_id = 1
JOIN store s ON s.store_id = 1
WHERE f.title = 'Academy Dinosaur'
GROUP BY f.title, s.store_id;

-- Provide a list of all distinct film titles, along with their availability status in the inventory. 
-- Include a column indicating whether each title is 'Available' or 'NOT available.' 
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE 
-- statement combined with IFNULL."

SELECT 
    f.title,
    CASE 
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM 
    film AS f
LEFT JOIN 
    inventory AS i ON f.film_id = i.film_id
GROUP BY 
    f.film_id, f.title
ORDER BY 
    f.title;
