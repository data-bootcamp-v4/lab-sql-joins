-- 1. List the number of films per category
SELECT * FROM category;
SELECT * FROM film_category;

SELECT c.name AS category, COUNT(fc.film_id) AS number_of_films
FROM category AS c
JOIN film_category AS fc
ON c.category_id = fc.category_id
GROUP BY c.name;

-- 2. Retrieve the store ID, city, and country for each store
SELECT * FROM store;
SELECT * FROM city;
SELECT * FROM country;
SELECT * FROM address;

SELECT s.store_id, c.city, co.country
FROM store AS s
JOIN address AS a
ON s.address_id = a.address_id
JOIN city as c
ON a.city_id = c.city_id
JOIN country as co
ON c.country_id = co.country_id;

-- 3. Calculate the total revenue generated by each store in dollars
SELECT * FROM payment;
SELECT * FROM staff;

SELECT SUM(p.amount) AS total_revenue, s.store_id AS store
FROM payment AS p
JOIN staff AS s
ON p.staff_id = s.staff_id
GROUP BY s.store_id;

-- 4. Determine the average running time of films for each category
SELECT * FROM film;
SELECT * FROM film_category;
SELECT * FROM category;

SELECT c.name AS category, ROUND(AVG(f.length), 0) AS avg_duration
FROM film AS f
JOIN film_category AS fc
ON f.film_id = fc.film_id
JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name;

-- 5. Identify the film categories with the longest average running time
SELECT c.name AS category, ROUND(AVG(f.length), 0) AS avg_duration
FROM film AS f
JOIN film_category AS fc
ON f.film_id = fc.film_id
JOIN category AS c
ON fc.category_id = c.category_id
GROUP BY c.name
ORDER BY avg_duration DESC;

-- 6. Display the top 10 most frequently rented movies in descending order
SELECT * FROM rental;
SELECT * FROM inventory;
SELECT * FROM film;

SELECT f.title AS most_rented_movies, COUNT(r.inventory_id) AS times_rented
FROM rental AS r
JOIN inventory AS i
ON r.inventory_id = i.inventory_id
JOIN film AS f
ON i.film_id = f.film_id
GROUP BY f.title
ORDER BY times_rented DESC
LIMIT 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1
SELECT * FROM inventory;
SELECT * FROM film;

SELECT f.title, i.store_id
FROM inventory as i
JOIN film as f
ON i.film_id = f.film_id
WHERE f.title = "ACADEMY DINOSAUR" AND i.store_id = 1;


