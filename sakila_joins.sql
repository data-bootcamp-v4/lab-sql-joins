-- 1. List the number of films per category.

SELECT 
    c.name AS category,
    COUNT(f.film_id) AS film_count
FROM sakila.category c
JOIN sakila.film_category fc ON c.category_id = fc.category_id
JOIN sakila.film f ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY film_count DESC;

-- 2. Retrieve the store ID, city, and country for each store.

SELECT 
	s.store_id,
	ci.city,
	co.country
FROM sakila.store s
JOIN sakila.address a ON s.address_id = a.address_id
JOIN sakila.city ci ON a.city_id = ci.city_id
JOIN sakila.country co ON ci.country_id = co.country_id

-- 3. Calculate the total revenue generated by each store in dollars.

SELECT 
    st.store_id,
    SUM(p.amount) AS total_revenue
FROM sakila.store st
JOIN sakila.staff sf ON st.store_id = sf.store_id
JOIN sakila.payment p ON sf.staff_id = p.staff_id
GROUP BY st.store_id
ORDER BY total_revenue DESC;

-- 4. Determine the average running time of films for each category.

SELECT 
    c.name AS category,
    AVG(f.length) AS avg_length
FROM sakila.category c
JOIN sakila.film_category fc ON c.category_id = fc.category_id
JOIN sakila.film f ON fc.film_id = f.film_id
GROUP BY c.name;

-- 5. Identify the film categories with the longest average running time.

SELECT 
    c.name AS category,
    AVG(f.length) AS avg_length
FROM sakila.category c
JOIN sakila.film_category fc ON c.category_id = fc.category_id
JOIN sakila.film f ON fc.film_id = f.film_id
GROUP BY c.name
ORDER BY avg_length DESC;

-- 6. Display the top 10 most frequently rented movies in descending order.

SELECT
	f.title,
	COUNT(r.rental_id) AS rental_count
FROM sakila.film f
JOIN sakila.inventory i ON f.film_id = i.film_id
JOIN sakila.rental r ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 10;

-- 7. Determine if "Academy Dinosaur" can be rented from Store 1.

SELECT 
    f.title,
    COUNT(i.film_id) AS available_copies
FROM sakila.film f
JOIN sakila.inventory i ON f.film_id = i.film_id
WHERE f.title = 'Academy Dinosaur'
	AND i.store_id = 1;

-- 8. Provide a list of all distinct film titles, along with their availability status in the inventory.
-- Include a column indicating whether each title is 'Available' or 'NOT available.'
-- Note that there are 42 titles that are not in the inventory, and this information can be obtained using a CASE statement combined with IFNULL."

SELECT 
    f.title,
    CASE 
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM sakila.film f
LEFT JOIN sakila.inventory i ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY f.title;
