USE sakila;

-- 1) List the number of films per category
SELECT
    c.name AS category,
    COUNT(fc.film_id) AS number_of_films
FROM category c
JOIN film_category fc
    ON c.category_id = fc.category_id
GROUP BY c.category_id, c.name
ORDER BY number_of_films DESC, category ASC;

-- 2) Retrieve the store ID, city, and country for each store
SELECT
    s.store_id,
    ci.city,
    co.country
FROM store s
JOIN address a
    ON s.address_id = a.address_id
JOIN city ci
    ON a.city_id = ci.city_id
JOIN country co
    ON ci.country_id = co.country_id
ORDER BY s.store_id ASC;

-- 3) Calculate the total revenue generated by each store in dollars
SELECT
    st.store_id,
    ROUND(SUM(p.amount), 2) AS total_revenue
FROM payment p
JOIN staff sf
    ON p.staff_id = sf.staff_id
JOIN store st
    ON sf.store_id = st.store_id
GROUP BY st.store_id
ORDER BY st.store_id ASC;

-- 4) Determine the average running time of films for each category
SELECT
    c.name AS category,
    ROUND(AVG(f.length), 2) AS average_running_time
FROM category c
JOIN film_category fc
    ON c.category_id = fc.category_id
JOIN film f
    ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY average_running_time DESC, category ASC;

-- BONUS 5) Identify the film categories with the longest average running time
SELECT
    category,
    average_running_time
FROM (
    SELECT
        c.name AS category,
        ROUND(AVG(f.length), 2) AS average_running_time
    FROM category c
    JOIN film_category fc
        ON c.category_id = fc.category_id
    JOIN film f
        ON fc.film_id = f.film_id
    GROUP BY c.category_id, c.name
) AS category_avg
WHERE average_running_time = (
    SELECT MAX(avg_length)
    FROM (
        SELECT ROUND(AVG(f.length), 2) AS avg_length
        FROM category c
        JOIN film_category fc
            ON c.category_id = fc.category_id
        JOIN film f
            ON fc.film_id = f.film_id
        GROUP BY c.category_id, c.name
    ) AS max_avg
)
ORDER BY category ASC;

-- BONUS 6) Display the top 10 most frequently rented movies in descending order
SELECT
    f.title,
    COUNT(r.rental_id) AS times_rented
FROM film f
JOIN inventory i
    ON f.film_id = i.film_id
JOIN rental r
    ON i.inventory_id = r.inventory_id
GROUP BY f.film_id, f.title
ORDER BY times_rented DESC, f.title ASC
LIMIT 10;

-- BONUS 7) Determine if "Academy Dinosaur" can be rented from Store 1
SELECT
    f.title,
    i.store_id,
    COUNT(i.inventory_id) AS copies_in_store,
    CASE
        WHEN COUNT(i.inventory_id) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film f
LEFT JOIN inventory i
    ON f.film_id = i.film_id
    AND i.store_id = 1
WHERE f.title = 'Academy Dinosaur'
GROUP BY f.film_id, f.title, i.store_id;

-- BONUS 8) List of all distinct film titles with inventory availability status
SELECT
    f.title,
    CASE
        WHEN IFNULL(inv.inventory_count, 0) > 0 THEN 'Available'
        ELSE 'NOT available'
    END AS availability_status
FROM film f
LEFT JOIN (
    SELECT
        film_id,
        COUNT(*) AS inventory_count
    FROM inventory
    GROUP BY film_id
) AS inv
    ON f.film_id = inv.film_id
ORDER BY f.title ASC;