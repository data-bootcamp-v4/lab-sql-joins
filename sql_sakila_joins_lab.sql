-- 1. List the number of films per category ---------------
-- Goal: For each category, count how many films belong to it.
-- Tables used:
-- - category (category names)
-- - film_category (bridge table between films and categories)
-- Join logic:
-- category.category_id = film_category.category_id
-- -------------------------------------------------------------------------
SELECT
  c.name AS category,
  COUNT(fc.film_id) AS number_of_films
FROM category AS c
JOIN film_category AS fc
  ON c.category_id = fc.category_id
GROUP BY c.category_id, c.name
ORDER BY number_of_films DESC;


-- ----------------------------------------------------------------
-- 2. Retrieve the store ID, city, and country for each store
-- Goal: For each store, show its store_id + location (city, country).
-- Tables used:
-- - store (store_id, address_id)
-- - address (city_id)
-- - city (country_id)
-- - country
-- Join chain:
-- store -> address -> city -> country
-- -----------------------------------------------------------
SELECT
  s.store_id,
  ci.city,
  co.country
FROM store AS s
JOIN address AS a
  ON s.address_id = a.address_id
JOIN city AS ci
  ON a.city_id = ci.city_id
JOIN country AS co
  ON ci.country_id = co.country_id
ORDER BY s.store_id;

-- ---------------------------------------------------------------
-- 3. Calculate the total revenue generated by each store (USD)
-- Goal: Sum all payment amounts per store.
-- Important: payment does NOT have store_id directly.
-- We must connect payments to a store through rentals + inventory.
-- Tables used:
-- - payment (amount, rental_id)
-- - rental (inventory_id)
-- - inventory (store_id)
-- Join chain:
-- payment -> rental -> inventory -> store_id
-- -----------------------------------------------

SELECT
  i.store_id,
  ROUND(SUM(p.amount), 2) AS total_revenue_usd
FROM payment AS p
JOIN rental AS r
  ON p.rental_id = r.rental_id
JOIN inventory AS i
  ON r.inventory_id = i.inventory_id
GROUP BY i.store_id
ORDER BY total_revenue_usd DESC;


-- ------------------------------------------------------------------
-- 4. Determine the average running time of films for each category
-- Goal: Average film.length grouped by category.
-- Tables used:
-- - category
-- - film_category
-- - film (length)
-- Join chain:
-- category -> film_category -> film
-- ---------------------------------------------

SELECT
  c.name AS category,
  ROUND(AVG(f.length), 2) AS avg_running_time
FROM category AS c
JOIN film_category AS fc
  ON c.category_id = fc.category_id
JOIN film AS f
  ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY avg_running_time DESC;


-- ------------------------------------------------------------------------------
-- BONUS 5.  Identify the film categories with the longest average running time
-- Goal: Same as 4, but only keep the category/categories on top.
-- Option A: show ONLY the #1 category (LIMIT 1)
-- ----------------------------------------------------------------------------

SELECT
  c.name AS category,
  ROUND(AVG(f.length), 2) AS avg_running_time
FROM category AS c
JOIN film_category AS fc
  ON c.category_id = fc.category_id
JOIN film AS f
  ON fc.film_id = f.film_id
GROUP BY c.category_id, c.name
ORDER BY avg_running_time DESC
LIMIT 1;


-- ------------------------------------------------------------------------------
-- BONUS 6. Display the top 10 most frequently rented movies (descending)
-- Goal: Count how many rentals each film has.
-- Tables used:
-- - rental (each row = one rental)
-- - inventory (links a rental to a film_id)
-- - film (title)
-- Join chain:
-- rental -> inventory -> film
-- ----------------------------------------------------------------------

SELECT
  f.title,
  COUNT(r.rental_id) AS times_rented
FROM rental AS r
JOIN inventory AS i
  ON r.inventory_id = i.inventory_id
JOIN film AS f
  ON i.film_id = f.film_id
GROUP BY f.film_id, f.title
ORDER BY times_rented DESC, f.title ASC
LIMIT 10;

-- -------------------------------------------------------------------
-- BONUS 7. Determine if "Academy Dinosaur" can be rented from Store 1
-- There are two common interpretations:
-- A) "Can be rented" = the store has at least 1 copy in inventory.
-- B) "Can be rented right now" = there is at least 1 copy NOT currently rented out.

-- I'll include both queries because instructors vary.
-- -------------------------------------------------------------------------------------

--  BONUS 7A) Check if Store 1 has the film in inventory ---------- 

SELECT
  f.title,
  i.store_id,
  COUNT(i.inventory_id) AS copies_in_inventory
FROM film AS f
JOIN inventory AS i
  ON f.film_id = i.film_id
WHERE f.title = 'Academy Dinosaur'
  AND i.store_id = 1
GROUP BY f.title, i.store_id;

--  BONUS 7B) Check if Store 1 has at least 1 copy available RIGHT NOW ----------
-- How it works:
-- - Start from inventory (copies available in the store)
-- - LEFT JOIN rentals that are still open (return_date IS NULL)
-- - If a copy has an open rental, it is currently rented out
-- - Available now = total copies - currently rented copies 

SELECT
  f.title,
  i.store_id,
  COUNT(i.inventory_id) AS total_copies,
  SUM(
    CASE 
      WHEN r.rental_id IS NOT NULL THEN 1 
      ELSE 0 
    END
  ) AS copies_currently_rented,
  (
    COUNT(i.inventory_id) - SUM(
      CASE 
        WHEN r.rental_id IS NOT NULL THEN 1 
        ELSE 0 
      END
    )
  ) AS copies_available_now
FROM film AS f
JOIN inventory AS i
  ON f.film_id = i.film_id
LEFT JOIN rental AS r
  ON i.inventory_id = r.inventory_id
  AND r.return_date IS NULL
WHERE f.title = 'Academy Dinosaur'
  AND i.store_id = 1
GROUP BY f.title, i.store_id;

-- ----------------------------------------------------------------------
-- BONUS 8. List all distinct film titles + availability status in inventory
-- Requirement:
-- - Show ALL films (even those NOT in inventory)
-- - Add a column: 'Available' or 'NOT available'
-- Important:
-- - We must start from film and LEFT JOIN inventory because there are films with zero inventory records.
-- - If COUNT(inventory_id) = 0 => NOT available
-- -------------------------------------------------------------------------------------------------------

SELECT
  f.title,
  CASE
    WHEN COUNT(i.inventory_id) = 0 THEN 'NOT available'
    ELSE 'Available'
  END AS availability
FROM film AS f
LEFT JOIN inventory AS i
  ON f.film_id = i.film_id
GROUP BY f.film_id, f.title
ORDER BY f.title;


